/// Provision `/system/fonts` **into the sysroot**, and the image's *other*
/// font sets with it.
///
/// `Typeface`/`SystemFonts` read `/system/etc/fonts.xml` (present in the
/// extracted sysroot) and the font files it names. On a device there are two
/// more font roots, neither of which the sandbox can see:
///
/// * `/product/fonts` + `/product/etc/fonts_customization.xml` (`google-sans`,
///   `google-sans-text`, ... — what the static RROs point
///   `config_*FontFamily` at), and
/// * the same pair under `/system_ext` and `/vendor`.
///
/// `tools/art-sysroot.sh` extracts all of them next to the partitions they come
/// from (`<sysroot>/{product,system_ext,vendor}/{fonts,etc}`), read-only and
/// without mounting anything. This function makes them reachable through the
/// **existing** `/system` bind:
///
/// 1. every partition font file is hard-linked into `<sysroot>/system/fonts`
///    (0 bytes copied; `fonts.xml` names files relative to `/system/fonts`),
/// 2. `new-named-family` entries of a `fonts_customization.xml` are merged into
///    `<sysroot>/system/etc/fonts.xml` with their paths rewritten to
///    `/system/fonts/<file>` (idempotent: a family whose name is already in the
///    config is not added twice). Other customization types
///    (`replace`, `additional-named-fallback`) would need the real
///    `/product/etc/fonts_customization.xml` path, which is a mount the sandbox
///    does not have; they are reported in the diagnostics, never silently
///    dropped.
///
/// Nothing here is bind-mounted at `/system/fonts`: bwrap cannot create a mount
/// point inside a read-only bind (`bwrap: Can't create file /system/fonts:
/// Read-only file system`). Undo with `rm -rf <sysroot>/system/fonts` (and
/// `git checkout`-free: the fonts.xml additions are regenerated from the base
/// file, which is left in place).
///
/// Without the `/system` set text layout produces nothing and `TextView`'s
/// constructor NPEs; the run is then reported as `NoSysroot`/`UNSUPPORTED`
/// rather than silently rendering blank text.
pub fn ensure_system_fonts(root: &ArtRoot, diagnostics: &mut Vec<String>) -> Result<PathBuf> {
    let dest = root.sysroot.join("system/fonts");
    let src = root.repo_root.join(".cache/boot/android-34/fonts");
    if !src.is_dir() {
        diagnostics.push(format!(
            "no system fonts: {} is missing (rebuild them with the boot-image extraction); \
             text will not render",
            src.display()
        ));
        return Ok(dest);
    }
    fs::create_dir_all(&dest)?;
    let mut linked = 0usize;
    let mut copied = 0usize;
    for e in fs::read_dir(&src)?.filter_map(|e| e.ok()) {
        let from = e.path();
        if !from.is_file() {
            continue;
        }
        let to = dest.join(e.file_name());
        if to.exists() {
            continue;
        }
        if fs::hard_link(&from, &to).is_ok() {
            linked += 1;
        } else {
            fs::copy(&from, &to)?;
            copied += 1;
        }
    }
    if let Some(xml) = src.join("fonts.xml").is_file().then(|| src.join("fonts.xml")) {
        let to = root.sysroot.join("system/etc/fonts.xml");
        if !to.is_file() {
            let _ = fs::hard_link(&xml, &to).or_else(|_| fs::copy(&xml, &to).map(|_| ()));
        }
    }
    let n_base = fs::read_dir(&dest).map(|d| d.count()).unwrap_or(0);

    // The image's other font roots (P3c): the same one-way provision, from the
    // partitions `tools/art-sysroot.sh` extracts next to `system/`.
    let base_xml = root.sysroot.join("system/etc/fonts.xml");
    let mut base = fs::read_to_string(&base_xml).unwrap_or_default();
    let mut extra = 0usize;
    let mut merged_families = 0usize;
    for part in ["product", "system_ext", "vendor"] {
        let pdir = root.sysroot.join(part);
        let fdir = pdir.join("fonts");
        if fdir.is_dir() {
            for e in fs::read_dir(&fdir)?.filter_map(|e| e.ok()) {
                let from = e.path();
                if !from.is_file() {
                    continue;
                }
                let to = dest.join(e.file_name());
                if to.exists() {
                    continue;
                }
                if fs::hard_link(&from, &to).is_ok() {
                    linked += 1;
                } else {
                    fs::copy(&from, &to)?;
                    copied += 1;
                }
                extra += 1;
            }
        }
        let cust = pdir.join("etc/fonts_customization.xml");
        if !cust.is_file() {
            continue;
        }
        match merge_font_customization(&base, &fs::read_to_string(&cust)?, &dest) {
            Ok((next, added, skipped)) => {
                if added > 0 {
                    base = next;
                    merged_families += added;
                }
                if skipped > 0 {
                    diagnostics.push(format!(
                        "{part}/etc/fonts_customization.xml: {skipped} family/ies use a \
                         customization type that needs the real /{part} mount (not applied; \
                         `new-named-family` only)"
                    ));
                }
            }
            Err(e) => diagnostics.push(format!(
                "{part}/etc/fonts_customization.xml: could not merge ({e}); \
                 families it declares will not resolve"
            )),
        }
    }
    if merged_families > 0 {
        fs::write(&base_xml, &base)?;
        diagnostics.push(format!(
            "merged {merged_families} product/system_ext/vendor font famil(y/ies) into {}",
            base_xml.display()
        ));
    }
    if extra > 0 {
        diagnostics.push(format!(
            "provisioned {extra} partition font(s) (product/system_ext/vendor) into {}",
            dest.display()
        ));
    }

    let n = fs::read_dir(&dest).map(|d| d.count()).unwrap_or(n_base);
    diagnostics.push(format!(
        "provisioned {n} system fonts into {} ({linked} hard links, {copied} copies)",
        dest.display()
    ));
    Ok(dest)
}

/// Merge `new-named-family` entries of a `fonts_customization.xml` into a
/// `fonts.xml` body, rewriting each `<font>` path to `/system/fonts/<basename>`
/// (the files themselves are hard-linked there by [`ensure_system_fonts`]).
///
/// Returns `(new_xml, added, skipped)`; families whose `name` already occurs in
/// `base` are not added again, so re-running is a no-op. Anything that is not a
/// plain `new-named-family` (or a `<font>` with no filename, or a font file that
/// is not in `fonts_dir`) is counted in `skipped` and left out — reported by the
/// caller, never silently mangled.
fn merge_font_customization(
    base: &str,
    customization: &str,
    fonts_dir: &Path,
) -> Result<(String, usize, usize)> {
    let close = base
        .rfind("</families>")
        .ok_or_else(|| Error::Layout("fonts.xml has no </families>".into()))?;
    let mut added_xml = String::new();
    let (mut added, mut skipped) = (0usize, 0usize);
    let mut rest = customization;
    while let Some(start) = rest.find("<family") {
        rest = &rest[start..];
        let Some(end) = rest.find("</family>") else { break };
        let block = &rest[..end + "</family>".len()];
        rest = &rest[end + "</family>".len()..];
        let open_end = block.find('>').unwrap_or(0);
        let open = &block[..=open_end];
        let is_new = open.contains("new-named-family");
        let name = open
            .find("name=\"")
            .and_then(|i| {
                let s = &open[i + 6..];
                s.find('"').map(|j| s[..j].to_string())
            })
            .unwrap_or_default();
        if !is_new || name.is_empty() {
            skipped += 1;
            continue;
        }
        if base.contains(&format!("name=\"{name}\"")) || added_xml.contains(&format!("name=\"{name}\"")) {
            continue;
        }
        // Rewrite every <font ...>path</font> to an absolute /system/fonts path.
        let mut out = open.to_string();
        let mut inner = &block[open_end + 1..end];
        let mut bad = false;
        loop {
            let Some(fs) = inner.find("<font") else { break };
            let before = &inner[..fs];
            let Some(fe) = inner[fs..].find("</font>").map(|i| i + fs) else {
                bad = true;
                break;
            };
            let font_open_end = inner[fs..].find('>').map(|i| i + fs).unwrap_or(fe);
            let path = inner[font_open_end + 1..fe].trim();
            let base_name = Path::new(path)
                .file_name()
                .map(|f| f.to_string_lossy().to_string())
                .unwrap_or_default();
            if base_name.is_empty() || !fonts_dir.join(&base_name).is_file() {
                bad = true;
                break;
            }
            out.push_str(before);
            out.push_str(&inner[fs..=font_open_end]);
            out.push_str(&format!("/system/fonts/{base_name}"));
            out.push_str("</font>");
            inner = &inner[fe + "</font>".len()..];
        }
        if bad {
            skipped += 1;
            continue;
        }
        out.push_str(inner);
        out.push_str("</family>\n");
        added_xml.push_str(&out);
        added += 1;
    }
    if added == 0 {
        return Ok((base.to_string(), 0, skipped));
    }
    let mut merged = String::with_capacity(base.len() + added_xml.len());
    merged.push_str(&base[..close]);
    merged.push_str("\n<!-- merged from the image's fonts_customization.xml by acos-art -->\n");
    merged.push_str(&added_xml);
    merged.push_str(&base[close..]);
    Ok((merged, added, skipped))
}

// ------------------------------------------------------- static RRO overlays

/// The image's **static** resource overlays, applied the way the device applies
/// them (`results/art-runtime/P2c.md`).
///
/// The overlay set is exactly what the boot-image extraction
/// (`tools/extract-bootclasspath.sh`) puts in `.cache/boot/android-34/overlays`:
/// the RROs whose binary manifest declares `android:isStatic="true"` and
/// `android:targetPackage="android"`. Nothing is hardcoded here — the manifests
/// are read with `aapt2` and the idmaps are produced by the image's own
/// `/system/bin/idmap2` inside the `acos-art` sandbox.
#[derive(Debug, Clone, Default)]
pub struct OverlaySet {
    /// On-device idmap paths, in application order (later wins on a clash).
    pub idmaps: Vec<String>,
    /// Host paths of the generated idmaps.
    pub host_idmaps: Vec<PathBuf>,
    /// Overlay APK file names that were applied.
    pub applied: Vec<String>,
    /// idmaps generated in this run.
    pub generated: usize,
    /// idmaps reused from the cache.
    pub cached: usize,
    /// Total size of the idmaps consumed at runtime, bytes.
    pub idmap_bytes: u64,
}

impl OverlaySet {
    pub fn is_empty(&self) -> bool {
        self.idmaps.is_empty()
    }

    /// The guest argument: `','`-separated on-device idmap paths (`""` = none).
    pub fn guest_arg(&self) -> String {
        self.idmaps.join(",")
    }
}

/// Provision the image's static RRO idmaps into `<data>/overlay` and return the
/// on-device paths the guest must hand to `ApkAssets.loadOverlayFromPath`.
///
/// Offline cost is paid once: an idmap is (re)generated only when the overlay
/// APK **or** the target `framework-res.apk` changes — the idmap carries both
/// CRCs, so keying on both is what makes a stale idmap impossible (P2c §7).
/// The generation itself is the device's own tool:
///
/// ```text
/// idmap2 create --policy product \
///   --target-apk-path  /system/framework/framework-res.apk \
///   --overlay-apk-path /data/overlay/<overlay>.apk \
///   --idmap-path       /data/overlay/<overlay>.idmap
/// ```
///
/// `--policy product` is mandatory: `framework-res` declares no `<overlayable>`
/// entries, so without a partition policy idmap2 rejects every resource and exits
/// with `no resources were overlaid` (P2c §4.1).
///
/// A missing extraction, target or `idmap2` is a *diagnostic*, not an error: the
/// app still renders, without the overlays (and then legitimately shows
/// `INCREMENT`, because nothing overrides the base `framework-res`).
pub fn provision_overlays(root: &ArtRoot, diagnostics: &mut Vec<String>) -> Result<OverlaySet> {
    let mut set = OverlaySet::default();
    let src = root.repo_root.join(".cache/boot/android-34/overlays");
    let target = root.sysroot.join("system/framework/framework-res.apk");
    if !src.is_dir() {
        diagnostics.push(format!(
            "no static overlays: {} is missing (re-run tools/extract-bootclasspath.sh); \
             rendering the un-overlaid framework resources",
            src.display()
        ));
        return Ok(set);
    }
    if !target.is_file() {
        diagnostics.push(format!(
            "no static overlays: {} is missing; rendering the un-overlaid resources",
            target.display()
        ));
        return Ok(set);
    }
    if !root.sysroot.join("system/bin/idmap2").is_file() {
        diagnostics.push(
            "no static overlays: the sysroot has no /system/bin/idmap2 (the image's own \
             idmap generator); rendering the un-overlaid resources"
                .to_string(),
        );
        return Ok(set);
    }

    let dest = root.data.join("overlay");
    fs::create_dir_all(&dest)?;
    let target_crc = fnv(0xcbf2_9ce4_8422_2325, &fs::read(&target)?);

    let mut apks: Vec<PathBuf> = fs::read_dir(&src)
        .map_err(|e| Error::Io(e))?
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| p.extension().map(|x| x == "apk").unwrap_or(false))
        .collect();
    apks.sort();

    for apk in apks {
        let name = apk
            .file_name()
            .map(|f| f.to_string_lossy().to_string())
            .unwrap_or_default();
        let stem = name.trim_end_matches(".apk").to_string();
        let bytes = match fs::read(&apk) {
            Ok(b) => b,
            Err(e) => {
                diagnostics.push(format!("overlay {name}: unreadable ({e}), skipped"));
                continue;
            }
        };
        let key = format!(
            "{}-{}-product",
            fnv(0xcbf2_9ce4_8422_2325, &bytes),
            target_crc
        );
        let idmap = dest.join(format!("{stem}.idmap"));
        let key_file = dest.join(format!("{stem}.idmap.key"));
        let fresh = idmap.is_file()
            && fs::read_to_string(&key_file)
                .map(|s| s.trim() == key)
                .unwrap_or(false);
        if fresh {
            set.cached += 1;
        } else {
            // Only the (re)generation path needs the manifest verdict.
            match is_static_android_overlay(&apk) {
                Ok(true) => {}
                Ok(false) => {
                    diagnostics.push(format!(
                        "overlay {name}: not isStatic/targetPackage=android, skipped"
                    ));
                    continue;
                }
                Err(e) => {
                    diagnostics.push(format!("overlay {name}: manifest unreadable ({e}), skipped"));
                    continue;
                }
            }
            stage_file(&apk, &dest.join(&name))?;
            let dev_overlay = format!("/data/overlay/{name}");
            let dev_idmap = format!("/data/overlay/{stem}.idmap");
            let argv: Vec<String> = [
                "create",
                "--policy",
                "product",
                "--target-apk-path",
                "/system/framework/framework-res.apk",
                "--overlay-apk-path",
                &dev_overlay,
                "--idmap-path",
                &dev_idmap,
            ]
            .iter()
            .map(|s| s.to_string())
            .collect();
            match sandbox_tool(root, "/system/bin/idmap2", &argv, 60) {
                Ok((status, _, _)) if status.success() && idmap.is_file() => {
                    fs::write(&key_file, format!("{key}\n"))?;
                    set.generated += 1;
                }
                Ok((status, out, err)) => {
                    diagnostics.push(format!(
                        "overlay {name}: idmap2 failed ({}): {}{}",
                        status,
                        tail(&out, 400),
                        tail(&err, 600)
                    ));
                    continue;
                }
                Err(e) => {
                    diagnostics.push(format!("overlay {name}: idmap2 could not run ({e})"));
                    continue;
                }
            }
        }
        if !dest.join(&name).is_file() {
            // The overlays' idmap names /data/overlay/<name>.apk; keep it staged
            // in case the cache outlives an external clean-up.
            stage_file(&apk, &dest.join(&name))?;
        }
        set.idmap_bytes += fs::metadata(&idmap).map(|m| m.len()).unwrap_or(0);
        set.idmaps.push(format!("/data/overlay/{stem}.idmap"));
        set.applied.push(name);
        set.host_idmaps.push(idmap);
    }

    diagnostics.push(format!(
        "static overlays: {} applied ({} idmaps generated, {} cached, {} B)",
        set.applied.len(),
        set.generated,
        set.cached,
        set.idmap_bytes
    ));
    Ok(set)
}

/// `aapt2 dump xmltree` on the overlay's binary manifest: does it declare
/// `<overlay android:targetPackage="android" android:isStatic="true">`?
fn is_static_android_overlay(apk: &Path) -> Result<bool> {
    let sdk = android_sdk()?;
    let aapt2 = find_tool(&sdk, "aapt2")?;
    let out = Command::new(&aapt2)
        .args(["dump", "xmltree", "--file", "AndroidManifest.xml"])
        .arg(apk)
        .output()?;
    if !out.status.success() {
        return Err(Error::Tool(format!(
            "aapt2 could not read {}: {}",
            apk.display(),
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    let text = String::from_utf8_lossy(&out.stdout);
    let (mut in_overlay, mut targets_android, mut is_static) = (false, false, false);
    for line in text.lines() {
        let t = line.trim_start();
        if t.starts_with("E: ") {
            in_overlay = t.starts_with("E: overlay");
            continue;
        }
        if !in_overlay {
            continue;
        }
        if line.contains(":targetPackage") && line.contains("\"android\"") {
            targets_android = true;
        }
        if line.contains(":isStatic") && line.contains("=true") {
            is_static = true;
        }
    }
    Ok(targets_android && is_static)
}

/// Hard-link `from` to `to` (same filesystem: both live under the repo), falling
/// back to a copy. Idempotent: an existing `to` is left alone.
fn stage_file(from: &Path, to: &Path) -> Result<()> {
    if to.is_file() {
        return Ok(());
    }
    if fs::hard_link(from, to).is_err() {
        fs::copy(from, to)?;
    }
    Ok(())
}

/// Run a sysroot tool inside the sandbox, bounded by `secs`, with its output.
fn sandbox_tool(
    root: &ArtRoot,
    program: &str,
    argv: &[String],
    secs: u64,
) -> Result<(std::process::ExitStatus, String, String)> {
    let mut sb = root.sandbox();
    // Host-side build step (idmap2). It writes /data/overlay, so it is the
    // shared-tree staging layout, never a per-run root.
    sb.staging(true);
    let mut cmd = sb.command(program, argv)?;
    cmd.stdin(Stdio::null()).stdout(Stdio::piped()).stderr(Stdio::piped());
    let mut child = cmd
        .spawn()
        .map_err(|e| Error::Tool(format!("spawning bwrap for {program}: {e}")))?;
    let started = Instant::now();
    loop {
        if let Some(status) = child.try_wait()? {
            let mut out = String::new();
            if let Some(mut p) = child.stdout.take() {
                let _ = p.read_to_string(&mut out);
            }
            let mut err = String::new();
            if let Some(mut p) = child.stderr.take() {
                let _ = p.read_to_string(&mut err);
            }
            return Ok((status, out, err));
        }
        if started.elapsed() >= Duration::from_secs(secs) {
            let _ = child.kill();
            let _ = child.wait();
            return Err(Error::Tool(format!("{program} timed out after {secs}s")));
        }
        std::thread::sleep(Duration::from_millis(5));
    }
}

// ------------------------------------------------------------------ guest dex

/// A built guest classpath.
#[derive(Debug, Clone)]
pub struct GuestDex {
    pub dex_dir: PathBuf,
    pub cached: bool,
}

/// Sources of the `render-app` guest: its own entry point and the natives it
/// calls, and nothing else. `guest/java/dev/acos/art` also holds the entry
/// points of the *other* commands (`LaunchMain`, `SessionMain`); those are
/// separate processes with separate classpaths, and compiling them here would
/// let an unrelated in-flight guest file break `render-app` (exactly what a
/// `LaunchMain` referencing a not-yet-present `dev.acos.e3g` did in P3c).
pub fn render_guest_sources() -> Vec<PathBuf> {
    let dir = PathBuf::from(GUEST_SOURCE).join("dev/acos/art");
    ["AppMain.java", "RenderNat.java"]
        .iter()
        .map(|f| dir.join(f))
        .filter(|p| p.is_file())
        .collect()
}

/// Build `dev.acos.art.AppMain` (javac + d8) into `<data>/app/guest`, cached by
/// source hash. Also returns the SDK paths used, for the result diagnostics.
pub fn build_guest(root: &ArtRoot) -> Result<GuestDex> {
    let src_dir = PathBuf::from(GUEST_SOURCE);
    let out_dir = root.data.join("app/guest");
    fs::create_dir_all(&out_dir)?;
    let sources = render_guest_sources();
    if sources.is_empty() {
        return Err(Error::Layout(format!("no guest Java sources under {}", src_dir.display())));
    }
    let mut hash = 0xcbf2_9ce4_8422_2325u64;
    for p in &sources {
        hash = fnv(hash, p.to_string_lossy().as_bytes());
        hash = fnv(hash, &fs::read(p)?);
    }
    let stamp = out_dir.join(".hash");
    let dex = out_dir.join("classes.dex");
    let up_to_date = dex.is_file()
        && fs::read_to_string(&stamp).map(|s| s.trim() == hash.to_string()).unwrap_or(false);
    if up_to_date {
        return Ok(GuestDex { dex_dir: out_dir, cached: true });
    }

    let sdk = android_sdk()?;
    let android_jar = sdk.join("platforms/android-34/android.jar");
    if !android_jar.is_file() {
        return Err(Error::Tool(format!(
            "no android.jar at {} (set ANDROID_SDK_ROOT)",
            android_jar.display()
        )));
    }
    let d8 = find_tool(&sdk, "d8")?;
    let classes = out_dir.join("classes");
    let _ = fs::remove_dir_all(&classes);
    fs::create_dir_all(&classes)?;
    let mut javac = Command::new(std::env::var("JAVAC").unwrap_or_else(|_| "javac".into()));
    javac
        .args(["-nowarn", "-source", "11", "-target", "11"])
        .arg("-cp")
        .arg(&android_jar)
        .arg("-d")
        .arg(&classes)
        .args(&sources);
    let out = javac.output()?;
    if !out.status.success() {
        return Err(Error::Tool(format!(
            "javac failed for the render-app guest:\n{}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    let class_files = walk(&classes, "class");
    let out = Command::new(&d8)
        .arg("--lib")
        .arg(&android_jar)
        .args(["--min-api", "34", "--output"])
        .arg(&out_dir)
        .args(&class_files)
        .output()?;
    if !out.status.success() || !dex.is_file() {
        return Err(Error::Tool(format!(
            "d8 failed for the render-app guest (status {:?}):\n{}{}",
            out.status.code(),
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    fs::write(&stamp, format!("{hash}\n"))?;
    let _ = fs::remove_dir_all(&classes);
    Ok(GuestDex { dex_dir: out_dir, cached: false })
}

/// Compile `shim/render_shim.c` with the NDK's bionic clang (cached by source
/// hash) into `<data>/app/libacosart.so`.
///
/// It has to be a *bionic* object: it is loaded into the ART process, calls
/// `dlsym` on bionic's linker namespace and is entered through JNI's `JNIEnv`.
pub fn build_render_shim(root: &ArtRoot) -> Result<PathBuf> {
    let dir = root.data.join("app");
    fs::create_dir_all(&dir)?;
    let out = dir.join("libacosart.so");
    let src = dir.join("render_shim.c");
    let hash = fnv(0xcbf2_9ce4_8422_2325, RENDER_SHIM_SOURCE.as_bytes());
    let stamp = dir.join("libacosart.hash");
    if out.is_file()
        && fs::read_to_string(&stamp).map(|s| s.trim() == hash.to_string()).unwrap_or(false)
    {
        return Ok(out);
    }
    fs::write(&src, RENDER_SHIM_SOURCE)?;
    let clang = ndk_clang()?;
    let st = Command::new(&clang)
        .args(["-O2", "-fPIC", "-shared", "-Wall", "-Wno-unused-parameter", "-o"])
        .arg(&out)
        .arg(&src)
        .arg("-ldl")
        .status()?;
    if !st.success() {
        return Err(Error::Tool(format!(
            "{} failed to build {}",
            clang.display(),
            src.display()
        )));
    }
    fs::write(&stamp, format!("{hash}\n"))?;
    Ok(out)
}

