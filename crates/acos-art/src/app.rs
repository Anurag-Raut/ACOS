pub(crate) fn android_sdk() -> Result<PathBuf> {
    for var in ["ANDROID_SDK_ROOT", "ANDROID_HOME"] {
        if let Some(p) = std::env::var_os(var) {
            let p = PathBuf::from(p);
            if p.join("platforms").is_dir() {
                return Ok(p);
            }
        }
    }
    if let Some(home) = std::env::var_os("HOME") {
        let p = PathBuf::from(home).join("Android/Sdk");
        if p.join("platforms").is_dir() {
            return Ok(p);
        }
    }
    Err(Error::Tool(
        "no Android SDK found (set ANDROID_SDK_ROOT; needs platforms/android-34/android.jar and build-tools/*/d8)"
            .into(),
    ))
}

pub(crate) fn find_tool(sdk: &Path, name: &str) -> Result<PathBuf> {
    let mut best: Option<(Vec<u32>, PathBuf)> = None;
    for e in fs::read_dir(sdk.join("build-tools")).map_err(|_| {
        Error::Tool(format!("no build-tools under {}", sdk.display()))
    })? {
        let e = e?;
        let p = e.path().join(name);
        if !p.is_file() {
            continue;
        }
        let ver: Vec<u32> = e
            .file_name()
            .to_string_lossy()
            .split('.')
            .map(|c| c.parse().unwrap_or(0))
            .collect();
        if best.as_ref().map(|(v, _)| ver > *v).unwrap_or(true) {
            best = Some((ver, p));
        }
    }
    best.map(|(_, p)| p)
        .ok_or_else(|| Error::Tool(format!("no {name} under {}/build-tools", sdk.display())))
}

fn ndk_clang() -> Result<PathBuf> {
    let mut roots: Vec<PathBuf> = Vec::new();
    if let Some(p) = std::env::var_os("ANDROID_NDK_HOME").or_else(|| std::env::var_os("ANDROID_NDK_ROOT")) {
        roots.push(PathBuf::from(p));
    }
    if let Ok(sdk) = android_sdk() {
        if let Ok(rd) = fs::read_dir(sdk.join("ndk")) {
            let mut v: Vec<PathBuf> = rd.filter_map(|e| e.ok()).map(|e| e.path()).collect();
            v.sort();
            v.reverse();
            roots.extend(v);
        }
    }
    for r in roots {
        let dir = r.join("toolchains/llvm/prebuilt/linux-x86_64/bin");
        for target in ["x86_64-linux-android34-clang", "x86_64-linux-android33-clang"] {
            let p = dir.join(target);
            if p.is_file() {
                return Ok(p);
            }
        }
    }
    if let Ok(cc) = std::env::var("CC") {
        return Ok(PathBuf::from(cc));
    }
    Err(Error::Tool(
        "no NDK clang found (set ANDROID_NDK_HOME; needs x86_64-linux-android34-clang)".into(),
    ))
}

/// The APK's package name, from `aapt2 dump packagename` (the SDK binary that
/// owns binary-manifest parsing).
pub fn apk_package(apk: &Path) -> Result<String> {
    let sdk = android_sdk()?;
    let aapt2 = find_tool(&sdk, "aapt2")?;
    let out = Command::new(&aapt2)
        .arg("dump")
        .arg("packagename")
        .arg(apk)
        .output()?;
    let name = String::from_utf8_lossy(&out.stdout).trim().to_string();
    if !out.status.success() || name.is_empty() {
        return Err(Error::Tool(format!(
            "aapt2 could not read the package of {}: {}{} (pass --package)",
            apk.display(),
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    Ok(name)
}

/// The layout resource to inflate: `main` when the APK has it, else
/// `activity_main`, else the first `layout/*` entry the APK ships.
/// The activity theme, application label and targetSdk from the APK's binary
/// manifest — the window chrome `PhoneWindow` needs and the guest must not
/// invent. Returns `(theme resource id as a hex string, label, targetSdk)`;
/// `0` means "no `android:theme`", i.e. the platform default, exactly as
/// `ActivityThread` treats a zero theme.
///
/// `aapt2` owns manifest parsing: `dump badging` for the label, `dump xmltree`
/// for the `android:theme` reference. Nothing is hardcoded per app.
pub fn apk_chrome(apk: &Path) -> Result<(String, String, u32)> {
    let sdk = android_sdk()?;
    let aapt2 = find_tool(&sdk, "aapt2")?;
    let badging = Command::new(&aapt2).arg("dump").arg("badging").arg(apk).output()?;
    if !badging.status.success() {
        return Err(Error::Tool(format!(
            "aapt2 could not read {}: {}",
            apk.display(),
            String::from_utf8_lossy(&badging.stderr).trim()
        )));
    }
    let badging = String::from_utf8_lossy(&badging.stdout);
    let label = badging
        .lines()
        .find_map(|l| l.strip_prefix("application-label:"))
        .map(|v| v.trim().trim_matches('\'').to_string())
        .filter(|v| !v.is_empty())
        .unwrap_or_else(|| {
            badging
                .lines()
                .find_map(|l| l.strip_prefix("package: name='"))
                .and_then(|v| v.split('\'').next().map(str::to_string))
                .unwrap_or_default()
        });

    let target_sdk = badging
        .lines()
        .find_map(|l| l.strip_prefix("targetSdkVersion:'"))
        .and_then(|v| v.split('\'').next())
        .and_then(|v| v.parse::<u32>().ok())
        .unwrap_or(0);

    let tree = Command::new(&aapt2)
        .args(["dump", "xmltree", "--file", "AndroidManifest.xml"])
        .arg(apk)
        .output()?;
    let mut theme = "0".to_string();
    if tree.status.success() {
        for line in String::from_utf8_lossy(&tree.stdout).lines() {
            let Some(idx) = line.find(":theme(") else { continue };
            let Some(eq) = line[idx..].find('=') else { continue };
            let value = line[idx + eq + 1..].trim().trim_start_matches('@');
            // Numeric resource ids are stable ACOS-wide (the manifest's
            // compile-time table); names would need a resource lookup.
            if value.starts_with("0x") || value.chars().all(|c| c.is_ascii_digit()) {
                theme = value.to_string();
                break;
            }
        }
    }
    Ok((theme, label, target_sdk))
}

fn pick_layout(apk: &Path, package: &str) -> Result<String> {
    let sdk = android_sdk()?;
    let aapt2 = find_tool(&sdk, "aapt2")?;
    let out = Command::new(&aapt2).arg("dump").arg("resources").arg(apk).output()?;
    let text = String::from_utf8_lossy(&out.stdout).to_string();
    let mut layouts: Vec<String> = Vec::new();
    for line in text.lines() {
        // aapt2 dump resources prints one of
        //   "resource 0x7f020000 layout/main"          (aapt2 >= 30)
        //   "resource 0x7f020000 pkg:layout/main"
        let Some(idx) = line
            .find(" layout/")
            .map(|i| i + " layout/".len())
            .or_else(|| line.find(&format!("{package}:layout/")).map(|i| i + package.len() + ":layout/".len()))
        else {
            continue;
        };
        let name = line[idx..].split_whitespace().next().unwrap_or("").to_string();
        if !name.is_empty() && !name.contains('/') && !layouts.contains(&name) {
            layouts.push(name);
        }
    }
    for want in ["main", "activity_main"] {
        if layouts.iter().any(|l| l == want) {
            return Ok(want.to_string());
        }
    }
    match layouts.first() {
        Some(l) => Ok(l.clone()),
        None => Err(Error::Tool(format!(
            "{} has no layout/ resources (pass --layout)",
            apk.display()
        ))),
    }
}

