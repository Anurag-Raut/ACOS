/// The guest Java source tree (`dev.acos.art.AppMain` + `RenderNat`).
pub const GUEST_SOURCE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/guest/java");
/// The substrate shim source (`dev.acos.art.RenderNat`'s JNI side).
pub const RENDER_SHIM_SOURCE: &str = include_str!("../shim/render_shim.c");

/// Guest class that does the inflate/layout/draw.
pub const GUEST_CLASS: &str = "dev.acos.art.AppMain";

/// Everything the renderer needs to be told.
#[derive(Debug, Clone)]
pub struct AppOpts {
    /// Host path of the APK.
    pub apk: PathBuf,
    /// Application package name; derived from the manifest when `None`.
    pub package: Option<String>,
    /// Layout resource name (default: `main`, then `activity_main`).
    pub layout: Option<String>,
    /// Output directory for `frame.png` / `tree.json`.
    pub out: Option<PathBuf>,
    /// Panel width in px (device oracle: 1080).
    pub width: u32,
    /// Window/display height in px (device oracle: 2400).
    pub panel_height: u32,
    /// The app *content* band height, kept for the P2a/P2e comparators
    /// (1080×2400 @ 420 dpi ⇒ 2337 − 275 = 2062). The frame is now the full
    /// window; this is metadata only.
    pub content_height: u32,
    /// Status bar inset in px (the oracle's `statusBarBackground` frame).
    pub status_inset: u32,
    /// Navigation bar inset in px (the oracle's `navigationBarBackground` frame).
    pub nav_inset: u32,
    pub density_dpi: u32,
    /// **Deprecated, no-op.** Kept so the CLI keeps parsing `--text-allcaps`.
    /// The value is never forced any more: the image's static overlays decide
    /// `config_buttonTextAllCaps`, exactly as on the device (P2c). A run with
    /// [`AllCaps::Theme`] reports that it asked for the old override.
    pub text_all_caps: AllCaps,
    pub timeout: Duration,
}

/// The retired `--text-allcaps` switch (see [`AppOpts::text_all_caps`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum AllCaps {
    /// The default; identical to [`AllCaps::Theme`] now that overlays decide.
    Device,
    /// Asks for the removed forced-off workaround; reported, not applied.
    Theme,
}

impl AllCaps {
    pub fn as_str(self) -> &'static str {
        match self {
            AllCaps::Device => "device",
            AllCaps::Theme => "theme",
        }
    }
}

impl Default for AppOpts {
    fn default() -> Self {
        Self {
            apk: PathBuf::new(),
            package: None,
            layout: None,
            out: None,
            width: 1080,
            panel_height: 2400,
            content_height: 2062,
            status_inset: 128,
            nav_inset: 63,
            density_dpi: 420,
            text_all_caps: AllCaps::Device,
            timeout: Duration::from_secs(120),
        }
    }
}

/// The structured result of one `render-app` run.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AppResult {
    /// `ok` only when a frame and a tree were written.
    pub outcome: Outcome,
    /// Stable code (`NO_LAYOUT`, `INFLATE_FAILED`, `NO_FONTS`, `GUEST_ERROR`,
    /// `ART_CRASH`, `TIMEOUT`, `UNSUPPORTED_SYSCALL`, …) or `None`.
    pub code: Option<String>,
    pub apk: String,
    pub package: String,
    pub layout: String,
    pub width: u32,
    pub panel_height: u32,
    pub content_height: u32,
    pub status_inset: u32,
    pub nav_inset: u32,
    pub density_dpi: u32,
    /// The image's static RROs applied to the resource path (idmap basenames).
    pub overlays: Vec<String>,
    /// Total bytes of the generated idmaps.
    pub idmap_bytes: u64,
    pub frame: Option<String>,
    pub tree: Option<String>,
    /// md5 of `frame.png` (repeatability without re-reading it).
    pub frame_md5: Option<String>,
    pub nodes: Option<u64>,
    pub draw_cold_us: Option<u64>,
    pub draw_warm_us: Option<u64>,
    pub nonbg_px: Option<u64>,
    pub guest_wall_ms: Option<u64>,
    pub wall_ms: u64,
    /// Peak RSS of the whole guest process (`VmHWM`), MiB.
    pub peak_rss_mb: Option<f64>,
    /// Guest stdout, truncated to the last 8 KiB (the `ACOSAPP` line, cause
    /// chains and stack traces of a failed rung live here).
    pub stdout: String,
    /// Guest stderr, truncated to the last 8 KiB.
    pub stderr: String,
    pub logs: Vec<crate::logd::LogEntry>,
    pub diagnostics: Vec<String>,
    /// The guest's own note stream (rung timings, downgrades, stub calls).
    pub notes: Vec<String>,
    pub argv: Vec<String>,
}

impl AppResult {
    pub fn succeeded(&self) -> bool {
        self.outcome == Outcome::Ok
    }
}

// ---------------------------------------------------------------- entry point

/// Render one frame of `opts.apk` and write `frame.png` + `tree.json`.
pub fn render_app(root: &ArtRoot, opts: &AppOpts) -> Result<AppResult> {
    if !opts.apk.is_file() {
        return Err(Error::Layout(format!("no APK at {}", opts.apk.display())));
    }
    root.ensure_data()?;
    root.ensure_linkerconfig(false)?;
    root.ensure_classpath_env(false)?;

    let mut diagnostics = Vec::new();
    ensure_system_fonts(root, &mut diagnostics)?;
    let overlays = provision_overlays(root, &mut diagnostics)?;
    if opts.text_all_caps == AllCaps::Theme {
        diagnostics.push(
            "--text-allcaps is a no-op: the image's static RROs decide \
             config_buttonTextAllCaps (the guest never forces it)"
                .to_string(),
        );
    }

    // Guest dex + substrate shim (both hash-cached).
    let guest = build_guest(root)?;
    let shim = build_render_shim(root)?;
    let art_shim = crate::build_shim(&root.data.join("shim"))?;

    // Private per-run data root (S4): the guest writes `/data/out/render-app`
    // inside it; the shared inputs (`/data/app`, `/data/overlay`, the boot
    // image, the property table, `/linkerconfig`) are read-only in the guest.
    let run = root.new_run_dir("render")?;

    // The APK and the guest classpath live under /data, which the sandbox
    // already binds read-write.
    let app_dir = root.data.join("app");
    fs::create_dir_all(&app_dir)?;
    let apk_name = opts
        .apk
        .file_name()
        .map(|f| f.to_string_lossy().to_string())
        .unwrap_or_else(|| "app.apk".to_string());
    let apk = app_dir.join(&apk_name);
    fs::copy(&opts.apk, &apk)?;

    let package = match &opts.package {
        Some(p) => p.clone(),
        None => apk_package(&opts.apk)?,
    };
    let layout = match &opts.layout {
        Some(l) => l.clone(),
        None => pick_layout(&opts.apk, &package)?,
    };
    // The window chrome is the APK's, not a renderer default: the activity
    // theme comes from the binary manifest (0 = platform default) and the
    // ActionBar title from the application label.
    let (theme, title, target_sdk) = apk_chrome(&opts.apk)?;

    // The guest always writes into the sandbox's /data staging dir; the
    // artefacts are copied to --out afterwards.
    let staging = run.dir("out").join("render-app");
    fs::create_dir_all(&staging)?;
    for stale in ["frame.png", "tree.json"] {
        let _ = fs::remove_file(staging.join(stale));
    }
    let out = opts.out.clone().unwrap_or_else(|| staging.clone());
    fs::create_dir_all(&out)?;

    let argv: Vec<String> = vec![
        "-cp".to_string(),
        "/data/app/guest/classes.dex".to_string(),
        GUEST_CLASS.to_string(),
        format!("/data/app/{apk_name}"),
        package.clone(),
        "/data/out/render-app".to_string(),
        opts.width.to_string(),
        opts.content_height.to_string(),
        opts.density_dpi.to_string(),
        // On-device idmap paths of the image's static RROs (','-separated).
        overlays.guest_arg(),
        // Window geometry + manifest-derived chrome (no bounds in the guest).
        opts.panel_height.to_string(),
        opts.status_inset.to_string(),
        opts.nav_inset.to_string(),
        theme,
        title,
        target_sdk.to_string(),
    ];

    // Property table (the art shim serves it) — Build.<clinit> needs the ABI
    // list, ResourcesImpl.updateConfiguration needs ro.build.version.sdk.
    crate::Props::android34().write(&root.data.join(crate::props::PROPS_FILE))?;

    let logd = Logd::start(&run.dir("socket")).map_err(Error::Io)?;
    let mut sb = root.sandbox();
    sb.run_root(run.path());
    // LD_PRELOAD is managed here (not by Sandbox::with_shim) so that the logd /
    // property shim and the substrate shim are loaded together, in this order.
    sb.with_shim(false);
    sb.ro_bind(&art_shim, "/data/shim/libartshim.so");
    sb.ro_bind(&shim, "/data/app/libacosart.so");
    // Software gralloc interposer (built into the sysroot by
    // `tools/art-sysroot.sh --shim`; G1). Loaded last, so the substrate's
    // libraries resolve against it.
    sb.ro_bind(&root.sysroot.join("shim/libacoshw.so"), "/data/libacoshw.so");
    sb.rw_bind(run.dir("socket"), "/dev/socket");
    sb.env(
        "LD_PRELOAD",
        "/data/shim/libartshim.so:/data/app/libacosart.so:/data/libacoshw.so",
    );
    sb.env("ACOSART_LOAD", "libandroid_runtime.so:libhwui.so");
    sb.env("ACOSART_BINDER_FAKE", "1");

    let dalvik = "/system/apex/com.android.art/bin/dalvikvm64";
    let mut cmd = sb.command(dalvik, &argv)?;
    unsafe {
        cmd.pre_exec(move || {
            libc::prctl(libc::PR_SET_PDEATHSIG, libc::SIGKILL as libc::c_ulong, 0, 0, 0);
            let core = libc::rlimit { rlim_cur: 0, rlim_max: 0 };
            libc::setrlimit(libc::RLIMIT_CORE, &core);
            let nofile = libc::rlimit { rlim_cur: 4096, rlim_max: 4096 };
            libc::setrlimit(libc::RLIMIT_NOFILE, &nofile);
            // The launcher's memory backstops are soft limits for *this* process;
            // ART needs terabytes of address space and is never the bounded one.
            crate::watchdog::relax_child_limits();
            Ok(())
        });
    }
    cmd.process_group(0);
    cmd.stdin(Stdio::null()).stdout(Stdio::piped()).stderr(Stdio::piped());
    let full_argv: Vec<String> =
        std::iter::once(dalvik.to_string()).chain(argv.iter().cloned()).collect();

    let started = Instant::now();
    let mut child = cmd
        .spawn()
        .map_err(|e| Error::Tool(format!("spawning bwrap: {e}")))?;
    let pid = child.id() as i32;
    // Bounded capture (R1): the guest's stdout/stderr are diagnostic tails, not
    // a data channel, so a printing loop costs at most the cap.
    let cap = stream_cap_from_env();
    let (tx, rx) = mpsc::channel::<(u8, TailBuffer)>();
    let out_pipe = child.stdout.take().expect("piped stdout");
    let tx_out = tx.clone();
    let out_thread = std::thread::spawn(move || {
        let buf = crate::capture::drain_to_tail(out_pipe, cap);
        let _ = tx_out.send((0u8, buf));
    });
    let err_pipe = child.stderr.take().expect("piped stderr");
    let tx_err = tx.clone();
    let err_thread = std::thread::spawn(move || {
        let buf = crate::capture::drain_to_tail(err_pipe, cap);
        let _ = tx_err.send((1u8, buf));
    });

    // The launcher's own ceiling (ACOS_ART_RSS_MAX, default 2 GiB). A leak the
    // caps do not know about ends as HOST_MEMORY_LIMIT, never as a kernel OOM.
    let dog = MemoryWatchdog::from_env();
    if let Some(d) = &dog {
        d.arm_process_group(pid);
    }

    let mut timed_out = false;
    let status = loop {
        match child.try_wait() {
            Ok(Some(status)) => break Some(status),
            Ok(None) => {}
            Err(e) => {
                let _ = child.kill();
                return Err(Error::Io(e));
            }
        }
        if let Some(d) = &dog {
            if d.trip().is_some() {
                let _ = child.wait();
                break None;
            }
        }
        if started.elapsed() >= opts.timeout {
            timed_out = true;
            unsafe {
                libc::kill(-pid, libc::SIGKILL);
                libc::kill(pid, libc::SIGKILL);
            }
            let _ = child.wait();
            break None;
        }
        std::thread::sleep(Duration::from_millis(5));
    };
    let wall_ms = started.elapsed().as_millis() as u64;

    let mut stdout_buf = TailBuffer::with_cap(cap);
    let mut stderr_buf = TailBuffer::with_cap(cap);
    for _ in 0..2 {
        match rx.recv_timeout(Duration::from_secs(3)) {
            Ok((0, b)) => stdout_buf = b,
            Ok((_, b)) => stderr_buf = b,
            Err(_) => break,
        }
    }
    let _ = out_thread.join();
    let _ = err_thread.join();
    drop(tx);

    let batch = logd.finish_capped();
    let log_stats = batch.stats;
    let log_first_dropped = batch.first_dropped.clone();
    let logs = batch.entries;
    let stdout = stdout_buf.to_text();
    let stderr = stderr_buf.to_text();

    // bwrap re-exits with 128+signal when the guest died of a signal.
    let raw_exit = status.and_then(|s| s.code());
    let exit = match raw_exit {
        Some(c) if (129..=192).contains(&c) => None,
        other => other,
    };
    let mut signal = status.and_then(|s| std::os::unix::process::ExitStatusExt::signal(&s));
    if signal.is_none() {
        if let Some(c) = raw_exit {
            if (129..=192).contains(&c) {
                signal = Some(c - 128);
            }
        }
    }
    let (mut outcome, mut code, mut diags) =
        launcher::classify(exit, signal, timed_out, &stderr, &logs, opts.timeout);
    if let Some(d) = &dog {
        if let Some(trip) = d.trip() {
            outcome = Outcome::Unsupported;
            code = Some(HOST_MEMORY_LIMIT.to_string());
            diags.push(format!(
                "{HOST_MEMORY_LIMIT}: launcher RSS {} MiB exceeded the {} MiB ceiling \
                 (ACOS_ART_RSS_MAX); guest process group {:?} killed",
                trip.rss_bytes / 1024 / 1024,
                trip.limit_bytes / 1024 / 1024,
                trip.killed_pgid
            ));
        }
    }
    // The provisioning diagnostics (fonts, static overlays) belong to the
    // result too; they used to be collected and dropped (P2e fix).
    diags.splice(0..0, diagnostics);

    // The guest's own verdict (one ACOSAPP <json> line) outranks the generic
    // exit classification: a guest exception with exit 1 is a renderer crash,
    // not a NONZERO_EXIT of some arbitrary DEX.
    let verdict = parse_guest_line(&stdout);
    let mut notes = Vec::new();
    let mut guest_wall_ms = None;
    let mut rss_mb = None;
    let mut draw = (None, None, None);
    let mut nodes = None;
    if let Some(g) = &verdict {
        // The guest echoes the panel it rendered at; a mismatch means the
        // arguments did not survive the sandbox, not a style difference.
        if (g.width, g.panel_height, g.density_dpi)
            != (Some(opts.width), Some(opts.panel_height), Some(opts.density_dpi))
        {
            diags.push(format!(
                "guest panel {:?}x{:?}@{:?} != requested {}x{}@{}",
                g.width, g.panel_height, g.density_dpi,
                opts.width, opts.panel_height, opts.density_dpi
            ));
        }
        if (g.status_inset, g.nav_inset)
            != (Some(opts.status_inset), Some(opts.nav_inset))
        {
            diags.push(format!(
                "guest insets {:?}/{:?} != requested {}/{}",
                g.status_inset, g.nav_inset, opts.status_inset, opts.nav_inset
            ));
        }
        notes = g.notes.clone();
        guest_wall_ms = g.wall_ms;
        rss_mb = g.peak_rss_kb.map(|kb| kb as f64 / 1024.0);
        draw = (g.draw_cold_us, g.draw_warm_us, g.nonbg_px);
        nodes = g.nodes;
        match g.outcome.as_str() {
            "ok" => {
                outcome = Outcome::Ok;
                code = None;
            }
            other => {
                outcome = if other == "unsupported" { Outcome::Unsupported } else { Outcome::Crash };
                code = g.code.clone().or(Some("GUEST_ERROR".into()));
                diags.push(format!("guest: {}", g.message.clone().unwrap_or_default()));
            }
        }
    }

    // The guest always writes into the sandbox's /data staging dir; honour
    // --out by copying the artefacts there. When --out is not given they are
    // already in the right place (copying a file onto itself would truncate it
    // and report the md5 of an empty file).
    let staged_frame = staging.join("frame.png");
    let staged_tree = staging.join("tree.json");
    let frame = out.join("frame.png");
    let tree = out.join("tree.json");
    if frame != staged_frame && staged_frame.is_file() {
        fs::copy(&staged_frame, &frame)?;
    }
    if tree != staged_tree && staged_tree.is_file() {
        fs::copy(&staged_tree, &tree)?;
    }
    let mut frame_md5 = None;
    if !frame.is_file() || !tree.is_file() {
        if outcome == Outcome::Ok {
            outcome = Outcome::Crash;
            code = Some("NO_OUTPUT".into());
            diags.push(format!(
                "guest reported ok but {} / {} missing",
                frame.display(),
                tree.display()
            ));
        }
        if let Some(g) = &verdict {
            diags.extend(g.diagnostics());
        }
    } else {
        frame_md5 = Some(md5_file(&frame)?);
    }
    let _ = (&art_shim, &apk);
    diags.push(log_stats.summary());
    if let Some(e) = &log_first_dropped {
        diags.push(format!(
            "logd: oldest entries dropped; first dropped was [{}] {}: {}",
            e.priority_name(),
            e.tag,
            crate::capture::head(&e.message, 200)
        ));
    }
    diags.push(format!(
        "guest dex: {} ({})",
        guest.dex_dir.display(),
        if guest.cached { "cached" } else { "built" }
    ));

    Ok(AppResult {
        outcome,
        code,
        apk: opts.apk.display().to_string(),
        package,
        layout,
        width: opts.width,
        panel_height: opts.panel_height,
        content_height: opts.content_height,
        status_inset: opts.status_inset,
        nav_inset: opts.nav_inset,
        density_dpi: opts.density_dpi,
        overlays: overlays.applied.clone(),
        idmap_bytes: overlays.idmap_bytes,
        frame: frame.is_file().then(|| frame.display().to_string()),
        tree: tree.is_file().then(|| tree.display().to_string()),
        frame_md5,
        nodes,
        draw_cold_us: draw.0,
        draw_warm_us: draw.1,
        nonbg_px: draw.2,
        guest_wall_ms,
        wall_ms,
        peak_rss_mb: rss_mb,
        stdout: crate::capture::tail_text(&stdout, 8192),
        stderr: crate::capture::tail_text(&stderr, 8192),
        logs,
        diagnostics: diags,
        notes,
        argv: full_argv,
    })
}

