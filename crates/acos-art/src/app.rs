//! `acos-art render-app` — an APK's first frame, on real ART, as data.
//!
//! Productised form of the E4H feasibility spike (`results/art-feasibility/E4H.md`):
//! one `dalvikvm64` in the acos-art `bwrap` sandbox inflates the APK's launcher
//! layout under a real `Theme`, measures/lays it out at the device's panel size
//! and draws it into a software `Bitmap` with stock `libhwui`/Skia — no zygote,
//! no `system_server`, no `servicemanager`, no `/dev/binder`, no GPU.
//!
//! Output (in `--out`, default `<data>/out`):
//!
//! | file | content |
//! |---|---|
//! | `frame.png` | the frame at `width × contentHeight` (the device's app content band) |
//! | `tree.json` | `{bounds, nodes:[{class,id,text,bounds,measured,padding,…}]}` |
//!
//! and one [`AppResult`] with the [`launcher::Outcome`], a stable `code`, the
//! guest's timings and the md5 of the PNG (repeatability is checkable without
//! re-reading the file).
//!
//! ## The resource path is the device's
//!
//! The `AssetManager` is assembled exactly as `ResourcesManager` does at zygote
//! time (P2c): one `ApkAssets` for `framework-res.apk`, one
//! `ApkAssets.loadOverlayFromPath(idmap)` per **static RRO the image applies**
//! and one `ApkAssets` for the app APK, handed to `AssetManager.Builder`. The
//! idmaps are generated by the image's own `/system/bin/idmap2` at provisioning
//! time ([`provision_overlays`], cached by overlay+target hash). This is what
//! turns `Button#inc` from 267 px (`INCREMENT`) into the oracle's 231 px
//! (`Increment`) with **no hardcoded attribute and no `textAllCaps` override**.
//!
//! ## The two workarounds left (both measured in E4H)
//!
//! 1. **Font map/defaults** — `Typeface.sSystemFontMap` is a *zygote artefact*
//!    (`sSystemFontMapSharedMemory`), so a bare `dalvikvm64` has an empty map and
//!    `TextView`'s constructor NPEs in `Typeface.create(null,0)`. The guest
//!    rebuilds the map/fallback map from `/system/fonts` the way zygote does
//!    (`SystemFonts.buildSystemTypefaces`), installs the default family with the
//!    @hide `Typeface.setDefault(Typeface)` (Java field **and** libhwui's
//!    `gDefaultTypeface`) **and** fills `sDefaults[0..3]`. The last one is not
//!    optional once the overlays are applied: the overlay points the theme at
//!    `google-sans-text`, which this image does not ship, and the device resolves
//!    that to `sDefaults[style]` (P2c §4.2). The font *files* are provisioned
//!    into the sysroot by [`ensure_system_fonts`] — see its doc comment for why
//!    the sandbox cannot bind them.
//! 2. **Ripple on a software canvas** — `RippleDrawable.draw()` SIGSEGVs the
//!    process inside libhwui (silent: no tombstone, no log line) unless the
//!    canvas is hardware accelerated. The guest downgrades every
//!    `RippleDrawable` to its content layer (`getDrawable(0)`) before drawing;
//!    a ripple is a pressed-state animation and the static frame *is* its
//!    content layer.
//!
//! ## The window chrome is the framework's
//!
//! The guest does not inflate the layout bare. It builds the activity window
//! the way `ActivityThread` does: a real `com.android.internal.policy.PhoneWindow`
//! over the activity theme (the manifest's `android:theme`, or — when the APK
//! declares none — `Resources.selectDefaultTheme(0, targetSdk)` =
//! `Theme.DeviceDefault.Light.DarkActionBar`), `setContentView(layout)` so stock
//! `installDecor`/`generateLayout`/`DecorView.onResourcesLoaded` produce the
//! DecorView, `ActionBarOverlayLayout`, `ActionBarContainer`, `Toolbar`, the
//! ActionBar title and `id/content`, then the window's insets
//! (`--status-inset`/`--nav-inset`, the oracle's system-bar frames) are
//! dispatched and the DecorView is measured/laid out at
//! `width × panelHeight`. The tree is dumped from the DecorView down, in device
//! coordinates, and `frame.png` is the full window frame.
//!
//! Three pieces of `ViewRootImpl`/`system_server` are substituted, each a
//! no-behaviour stand-in, never a different answer:
//! `WindowManagerImpl` (the local window manager `Window.setWindowManager`
//! expects), a read-only local `settings` provider in
//! `ActivityThread.mProviderMap` (the `Settings.Global` int `PhoneWindow`'s
//! constructor reads, with unset keys falling through to the caller's default),
//! and a minimal `View$AttachInfo`/zeroed `ViewRootImpl` (only
//! `requestInvalidateRootRenderNode()` is reached).
//!
//! (`View.<init>`'s `IWindowManager` call is answered by a reflective `Proxy`.)
//!
//! Never fake: a missing sysroot/SDK/overlay, an APK without a launcher layout,
//! a guest exception and an ART crash are all structured, never a silent
//! fallback.

