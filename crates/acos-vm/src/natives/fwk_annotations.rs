fn mirror_mid(vm: &Vm, ctx: NativeCtx) -> Option<MethodId> {
    let this = vm.ctx_this(ctx).unwrap_or(NULL);
    mirror_method_id(vm, this)
}

fn ex_get_method_name(vm: &mut Vm, ctx: NativeCtx) -> VmResult<()> {
    match mirror_mid(vm, ctx) {
        Some(mid) => {
            let name = vm.methods[mid as usize].name.clone();
            // `Method.equals` compares `getName()` results by reference, so the
            // name must be the interned DEX string (ART interns it too).
            let h = vm.intern_str(&name)?;
            vm.ret_ref(ctx, h);
        }
        None => vm.ret_ref(ctx, NULL),
    }
    Ok(())
}

fn ex_get_method_return_type(vm: &mut Vm, ctx: NativeCtx) -> VmResult<()> {
    match mirror_mid(vm, ctx) {
        Some(mid) => {
            let ret = vm.methods[mid as usize].ret;
            let desc = vm.type_desc(ret).to_string();
            let cid = vm.load_class(&desc)?;
            let h = vm.class_object(cid)?;
            vm.ret_ref(ctx, h);
        }
        None => vm.ret_ref(ctx, NULL),
    }
    Ok(())
}

fn ex_get_parameter_types(vm: &mut Vm, ctx: NativeCtx) -> VmResult<()> {
    let params = match mirror_mid(vm, ctx) {
        Some(mid) => vm.methods[mid as usize].params.clone(),
        None => Vec::new(),
    };
    let base = vm.native_roots.len();
    let mut elems = Vec::new();
    for tid in params {
        let desc = vm.type_desc(tid).to_string();
        let cid = vm.load_class(&desc)?;
        let h = vm.class_object(cid)?;
        vm.native_roots.push(h);
        elems.push(h);
    }
    let arr = make_ref_array(vm, "Ljava/lang/Class;", elems)?;
    vm.native_roots.truncate(base);
    vm.ret_ref(ctx, arr);
    Ok(())
}

/// `Executable.compareMethodParametersInternal(Method)` — compare parameter
/// type lists (used to order proxy methods).
fn ex_compare_parameters(vm: &mut Vm, ctx: NativeCtx) -> VmResult<()> {
    let this = vm.ctx_this(ctx).unwrap_or(NULL);
    let other = vm.arg_ref(ctx, 0);
    let a = mirror_method_id(vm, this)
        .map(|mid| vm.methods[mid as usize].params.clone())
        .unwrap_or_default();
    let b = mirror_method_id(vm, other)
        .map(|mid| vm.methods[mid as usize].params.clone())
        .unwrap_or_default();
    let mut out = a.len() as i32 - b.len() as i32;
    if out == 0 {
        for (x, y) in a.iter().zip(&b) {
            let dx = vm.type_desc(*x).to_string();
            let dy = vm.type_desc(*y).to_string();
            if dx != dy {
                out = dy.cmp(&dx) as i32;
                break;
            }
        }
    }
    vm.ret_i32(ctx, out);
    Ok(())
}

fn ex_get_parameter_count(vm: &mut Vm, ctx: NativeCtx) -> VmResult<()> {
    let n = mirror_mid(vm, ctx)
        .map(|mid| vm.methods[mid as usize].params.len() as i32)
        .unwrap_or(0);
    vm.ret_i32(ctx, n);
    Ok(())
}

