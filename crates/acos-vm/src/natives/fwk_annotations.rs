/// `Method.getDefaultValue()` — decode `@dalvik.annotation.AnnotationDefault`.
fn method_get_default_value(vm: &mut Vm, ctx: NativeCtx) -> VmResult<()> {
    let this = vm.ctx_this(ctx).unwrap_or(NULL);
    let Some(mid) = mirror_method_id(vm, this) else {
        vm.ret_ref(ctx, NULL);
        return Ok(());
    };
    let cid = vm.methods[mid as usize].class;
    let method_name = vm.methods[mid as usize].name.clone();
    let ret_desc = vm.methods[mid as usize].ret;
    let ret_desc = vm.type_desc(ret_desc).to_string();
    // The default lives on the *annotation interface class* as
    // `@dalvik.annotation.AnnotationDefault(@TheAnnotation(name=..., ...))`.
    let Some((dex, _)) = class_dex_def(vm, cid) else {
        vm.ret_ref(ctx, NULL);
        return Ok(());
    };
    let file = vm.dexs[dex as usize].file.clone();
    let anns = annotations_of_class(vm, cid);
    let Some(ann) = find_annotation(&anns, &file, ANNOTATION_DEFAULT, VISIBILITY_SYSTEM)
        .or_else(|| find_annotation(&anns, &file, ANNOTATION_DEFAULT, VISIBILITY_RUNTIME))
    else {
        vm.ret_ref(ctx, NULL);
        return Ok(());
    };
    let Some(elem) = ann.elements().first() else {
        vm.ret_ref(ctx, NULL);
        return Ok(());
    };
    let EncodedValue::Annotation(defaults) = &elem.value else {
        vm.ret_ref(ctx, NULL);
        return Ok(());
    };
    let Some(entry) = defaults.elements.iter().find(|e| {
        file.string(e.name_idx)
            .map(|n| n == method_name)
            .unwrap_or(false)
    }) else {
        vm.ret_ref(ctx, NULL);
        return Ok(());
    };
    let h = decode_value(vm, &file, &entry.value, &ret_desc)?;
    vm.ret_ref(ctx, h);
    Ok(())
}

