/// Decode one `encoded_value` into the Java object of the declared type.
pub(crate) fn decode_value(
    vm: &mut Vm,
    file: &Arc<DexFile>,
    value: &EncodedValue,
    expected: &str,
) -> VmResult<Handle> {
    match value {
        EncodedValue::Boolean(b) => box_primitive(vm, 'Z', *b as u64),
        EncodedValue::Byte(b) => box_primitive(vm, 'B', *b as i64 as u64),
        EncodedValue::Short(s) => box_primitive(vm, 'S', *s as i64 as u64),
        EncodedValue::Char(c) => box_primitive(vm, 'C', *c as u64),
        EncodedValue::Int(i) => box_primitive(vm, 'I', *i as i64 as u64),
        EncodedValue::Long(l) => box_primitive(vm, 'J', *l as u64),
        EncodedValue::Float(f) => box_primitive(vm, 'F', *f as u64),
        EncodedValue::Double(d) => box_primitive(vm, 'D', *d),
        EncodedValue::Null => Ok(NULL),
        EncodedValue::String(idx) => {
            let s = file.string(*idx)?.to_string();
            vm.new_string(&s)
        }
        EncodedValue::Type(idx) => {
            let desc = file.type_descriptor(*idx)?.to_string();
            let cid = vm.load_class(&desc)?;
            vm.class_object(cid)
        }
        EncodedValue::Enum(idx) => {
            let fr = file.field_ref(*idx)?;
            let enum_desc = fr.class.to_string();
            let const_name = fr.name.to_string();
            let cid = vm.load_class(&enum_desc)?;
            vm.initialize_class(cid)?;
            let slot = vm.classes[cid as usize]
                .declared_static_fields
                .iter()
                .find(|f| f.name == const_name)
                .map(|f| f.offset as usize);
            match slot {
                Some(off) => Ok(vm.classes[cid as usize]
                    .statics
                    .get(off)
                    .copied()
                    .unwrap_or(0)),
                None => Ok(NULL),
            }
        }
        EncodedValue::Array(vals) => {
            let component = expected.strip_prefix('[').unwrap_or("Ljava/lang/Object;");
            make_annotation_array(vm, file, component, vals)
        }
        EncodedValue::Annotation(nested) => {
            let desc = file.type_descriptor(nested.type_idx)?.to_string();
            let cid = vm.load_class(&desc)?;
            let ann = Annotation {
                visibility: VISIBILITY_RUNTIME,
                annotation: nested.clone(),
            };
            make_annotation(vm, file, cid, &ann)
        }
        other => Err(VmError::unsupported_api(
            format!("annotation element value {other:?}"),
            "acos_vm::natives::fwk_annotations",
        )),
    }
}

fn make_annotation_array(
    vm: &mut Vm,
    file: &Arc<DexFile>,
    component: &str,
    vals: &[EncodedValue],
) -> VmResult<Handle> {
    vm.check_array_len(component, vals.len())?;
    match component.as_bytes().first().copied() {
        Some(b'Z') | Some(b'B') | Some(b'S') | Some(b'C') | Some(b'I') | Some(b'J')
        | Some(b'F') | Some(b'D') => {
            let mut data = new_array_data(component, vals.len())?;
            for (i, v) in vals.iter().enumerate() {
                set_prim(&mut data, i, v);
            }
            vm.alloc(Object::Array(ArrayObj {
                elem_desc: component.to_string(),
                data,
            }))
        }
        _ => {
            let base = vm.native_roots.len();
            let mut elems = Vec::new();
            for v in vals {
                let h = decode_value(vm, file, v, component)?;
                vm.native_roots.push(h);
                elems.push(h);
            }
            let arr = vm.alloc(Object::Array(ArrayObj {
                elem_desc: component.to_string(),
                data: ArrayData::Ref(elems),
            }));
            vm.native_roots.truncate(base);
            arr
        }
    }
}

fn set_prim(data: &mut ArrayData, i: usize, v: &EncodedValue) {
    match data {
        ArrayData::Bool(d) => {
            if let EncodedValue::Boolean(b) = v {
                d[i] = *b;
            }
        }
        ArrayData::Byte(d) => {
            if let EncodedValue::Byte(b) = v {
                d[i] = *b;
            }
        }
        ArrayData::Char(d) => {
            if let EncodedValue::Char(c) = v {
                d[i] = *c;
            }
        }
        ArrayData::Short(d) => {
            if let EncodedValue::Short(s) = v {
                d[i] = *s;
            }
        }
        ArrayData::Int(d) => {
            if let EncodedValue::Int(x) = v {
                d[i] = *x;
            }
        }
        ArrayData::Long(d) => {
            if let EncodedValue::Long(x) = v {
                d[i] = *x;
            }
        }
        ArrayData::Float(d) => {
            if let EncodedValue::Float(x) = v {
                d[i] = f32::from_bits(*x);
            }
        }
        ArrayData::Double(d) => {
            if let EncodedValue::Double(x) = v {
                d[i] = f64::from_bits(*x);
            }
        }
        ArrayData::Ref(_) => {}
    }
}

/// Box a primitive exactly as `java.lang.*.valueOf` does.
pub(crate) fn box_primitive(vm: &mut Vm, kind: char, raw: u64) -> VmResult<Handle> {
    let (class, sig) = match kind {
        'Z' => ("Ljava/lang/Boolean;", "(Z)Ljava/lang/Boolean;"),
        'B' => ("Ljava/lang/Byte;", "(B)Ljava/lang/Byte;"),
        'C' => ("Ljava/lang/Character;", "(C)Ljava/lang/Character;"),
        'S' => ("Ljava/lang/Short;", "(S)Ljava/lang/Short;"),
        'I' => ("Ljava/lang/Integer;", "(I)Ljava/lang/Integer;"),
        'J' => ("Ljava/lang/Long;", "(J)Ljava/lang/Long;"),
        'F' => ("Ljava/lang/Float;", "(F)Ljava/lang/Float;"),
        'D' => ("Ljava/lang/Double;", "(D)Ljava/lang/Double;"),
        _ => {
            return Err(VmError::Internal(format!(
                "box_primitive: unknown kind {kind:?}"
            )))
        }
    };
    let cid = vm.load_class(class)?;
    let mid = vm.find_method(cid, "valueOf", sig, InvokeKind::Static)?;
    Ok(crate::interp::call_method(vm, mid, NULL, &[raw])? as u32)
}

/// Unbox a boxed primitive to its raw slot value.
pub(crate) fn unbox_primitive(vm: &mut Vm, kind: char, obj: Handle) -> VmResult<u64> {
    if obj == NULL {
        return Err(vm.throw_new("Ljava/lang/NullPointerException;", None));
    }
    let (method, sig) = match kind {
        'Z' => ("booleanValue", "()Z"),
        'B' => ("byteValue", "()B"),
        'C' => ("charValue", "()C"),
        'S' => ("shortValue", "()S"),
        'I' => ("intValue", "()I"),
        'J' => ("longValue", "()J"),
        'F' => ("floatValue", "()F"),
        'D' => ("doubleValue", "()D"),
        _ => {
            return Err(VmError::Internal(format!(
                "unbox_primitive: unknown kind {kind:?}"
            )))
        }
    };
    let cid = vm
        .class_of_object(obj)
        .ok_or_else(|| vm.throw_new("Ljava/lang/IllegalArgumentException;", None))?;
    let mid = vm.find_method(cid, method, sig, InvokeKind::Virtual)?;
    crate::interp::call_method(vm, mid, obj, &[])
}
