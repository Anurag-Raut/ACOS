/// `Field.getNameInternal()` — interned, as ART does.
fn field_get_name_internal(vm: &mut Vm, ctx: NativeCtx) -> VmResult<()> {
    let this = vm.ctx_this(ctx).unwrap_or(NULL);
    match field_identity(vm, this) {
        Some((_, name)) => {
            let h = vm.intern_str(&name)?;
            vm.ret_ref(ctx, h);
        }
        None => vm.ret_ref(ctx, NULL),
    }
    Ok(())
}

