enum AnnotationOwner<'a> {
    Class,
    Field(&'a str),
    Method(u32),
}

fn annotation_present(
    vm: &mut Vm,
    cid: ClassId,
    target_h: Handle,
    owner: AnnotationOwner<'_>,
) -> bool {
    let Some(target) = vm.class_id_of_class_object(target_h) else {
        return false;
    };
    let target_desc = vm.class_desc(target).to_string();
    let (anns, dex) = match owner {
        AnnotationOwner::Class => (annotations_of_class(vm, cid), class_dex_def(vm, cid)),
        AnnotationOwner::Field(name) => {
            (annotations_of_field(vm, cid, name), class_dex_def(vm, cid))
        }
        AnnotationOwner::Method(midx) => {
            (annotations_of_method(vm, cid, midx), class_dex_def(vm, cid))
        }
    };
    let Some((dex, _)) = dex else {
        return false;
    };
    let file = vm.dexs[dex as usize].file.clone();
    find_annotation(&anns, &file, &target_desc, VISIBILITY_RUNTIME).is_some()
}

/// `(declaring class, field name)` for a `Field` mirror.
fn field_identity(vm: &Vm, this: Handle) -> Option<(ClassId, String)> {
    let dc = vm.get_instance_field_by_name(this, "declaringClass")?;
    let cid = vm.class_id_of_class_object(dc)?;
    let idx = vm
        .get_instance_field_by_name(this, "artFieldIndex")
        .unwrap_or(0) as usize;
    let access = vm
        .get_instance_field_by_name(this, "accessFlags")
        .unwrap_or(0);
    let c = &vm.classes[cid as usize];
    let def = if access & acos_dex::access::STATIC != 0 {
        c.declared_static_fields.get(idx)
    } else {
        c.declared_instance_fields.get(idx)
    };
    def.map(|d| (cid, d.name.clone()))
}

/// `(declaring class, DEX method index)` for a `Method`/`Constructor` mirror.
fn executable_identity(vm: &Vm, ctx: NativeCtx) -> Option<(ClassId, u32)> {
    let mid = mirror_mid(vm, ctx)?;
    let cid = vm.methods[mid as usize].class;
    let (_, method_idx) = dex_method(vm, mid)?;
    Some((cid, method_idx))
}

