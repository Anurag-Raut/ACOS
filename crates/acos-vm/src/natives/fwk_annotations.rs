fn cl_get_declared_annotation(vm: &mut Vm, ctx: NativeCtx) -> VmResult<()> {
    let Some(cid) = class_id(vm, ctx) else {
        vm.ret_ref(ctx, NULL);
        return Ok(());
    };
    let target_h = vm.arg_ref(ctx, 0);
    let Some(target) = vm.class_id_of_class_object(target_h) else {
        vm.ret_ref(ctx, NULL);
        return Ok(());
    };
    let target_desc = vm.class_desc(target).to_string();
    let anns = annotations_of_class(vm, cid);
    let Some((dex, _)) = class_dex_def(vm, cid) else {
        vm.ret_ref(ctx, NULL);
        return Ok(());
    };
    let file = vm.dexs[dex as usize].file.clone();
    match find_annotation(&anns, &file, &target_desc, VISIBILITY_RUNTIME) {
        Some(ann) => {
            let h = make_annotation(vm, &file, target, &ann)?;
            vm.ret_ref(ctx, h);
        }
        None => vm.ret_ref(ctx, NULL),
    }
    Ok(())
}

