fn class_id(vm: &Vm, ctx: NativeCtx) -> Option<ClassId> {
    let this = vm.ctx_this(ctx).unwrap_or(NULL);
    vm.class_id_of_class_object(this)
}

fn cl_get_declared_methods(vm: &mut Vm, ctx: NativeCtx) -> VmResult<()> {
    let public_only = vm.arg_bool(ctx, 0);
    let Some(cid) = class_id(vm, ctx) else {
        let h = make_ref_array(vm, "Ljava/lang/reflect/Method;", Vec::new())?;
        vm.ret_ref(ctx, h);
        return Ok(());
    };
    let base = vm.native_roots.len();
    let declared = vm.classes[cid as usize].declared_methods.clone();
    let mut elems = Vec::new();
    for mid in declared {
        let m = &vm.methods[mid as usize];
        if m.name == "<init>" || m.name == "<clinit>" {
            continue;
        }
        if public_only && m.access & acos_dex::access::PUBLIC == 0 {
            continue;
        }
        let h = make_method(vm, cid, mid)?;
        vm.native_roots.push(h);
        elems.push(h);
    }
    let arr = make_ref_array(vm, "Ljava/lang/reflect/Method;", elems)?;
    vm.native_roots.truncate(base);
    vm.ret_ref(ctx, arr);
    Ok(())
}

fn cl_get_declared_constructors(vm: &mut Vm, ctx: NativeCtx) -> VmResult<()> {
    let public_only = vm.arg_bool(ctx, 0);
    let Some(cid) = class_id(vm, ctx) else {
        let h = make_ref_array(vm, "Ljava/lang/reflect/Constructor;", Vec::new())?;
        vm.ret_ref(ctx, h);
        return Ok(());
    };
    let base = vm.native_roots.len();
    let declared = vm.classes[cid as usize].declared_methods.clone();
    let mut elems = Vec::new();
    for mid in declared {
        let m = &vm.methods[mid as usize];
        if m.name != "<init>" {
            continue;
        }
        if public_only && m.access & acos_dex::access::PUBLIC == 0 {
            continue;
        }
        let h = make_constructor(vm, cid, mid)?;
        vm.native_roots.push(h);
        elems.push(h);
    }
    let arr = make_ref_array(vm, "Ljava/lang/reflect/Constructor;", elems)?;
    vm.native_roots.truncate(base);
    vm.ret_ref(ctx, arr);
    Ok(())
}

/// `Class.getDeclaredConstructorInternal(Class[])` — declared-constructor
/// lookup by parameter types.
fn cl_get_declared_constructor(vm: &mut Vm, ctx: NativeCtx) -> VmResult<()> {
    let param_arr = vm.arg_ref(ctx, 0);
    let param_descs = class_array_descs(vm, param_arr);
    let Some(cid) = class_id(vm, ctx) else {
        vm.ret_ref(ctx, NULL);
        return Ok(());
    };
    let declared = vm.classes[cid as usize].declared_methods.clone();
    for mid in declared {
        let m = &vm.methods[mid as usize];
        if m.name != "<init>" || m.params.len() != param_descs.len() {
            continue;
        }
        let ok = m
            .params
            .iter()
            .zip(&param_descs)
            .all(|(&tid, want)| vm.type_desc(tid) == want);
        if ok {
            let h = make_constructor(vm, cid, mid)?;
            vm.ret_ref(ctx, h);
            return Ok(());
        }
    }
    vm.ret_ref(ctx, NULL);
    Ok(())
}

/// `Class.getDeclaredMethodInternal(String, Class[])` — declared-method lookup
/// by name and parameter types (no inherited search; the Java layer does that).
fn cl_get_declared_method(vm: &mut Vm, ctx: NativeCtx) -> VmResult<()> {
    let name = vm.string_to_rust(vm.arg_ref(ctx, 0)).unwrap_or_default();
    let param_arr = vm.arg_ref(ctx, 1);
    let param_descs = class_array_descs(vm, param_arr);
    let Some(cid) = class_id(vm, ctx) else {
        vm.ret_ref(ctx, NULL);
        return Ok(());
    };
    let declared = vm.classes[cid as usize].declared_methods.clone();
    for mid in declared {
        let m = &vm.methods[mid as usize];
        if m.name != name || m.params.len() != param_descs.len() {
            continue;
        }
        let ok = m
            .params
            .iter()
            .zip(&param_descs)
            .all(|(&tid, want)| vm.type_desc(tid) == want);
        if ok {
            let h = make_method(vm, cid, mid)?;
            vm.ret_ref(ctx, h);
            return Ok(());
        }
    }
    vm.ret_ref(ctx, NULL);
    Ok(())
}

/// Descriptors of the `Class` objects in a `Class[]`.
pub(crate) fn class_array_descs(vm: &Vm, arr: Handle) -> Vec<String> {
    let elems = match vm.heap.get(arr) {
        Some(Object::Array(a)) => match &a.data {
            ArrayData::Ref(v) => v.clone(),
            _ => return Vec::new(),
        },
        _ => return Vec::new(),
    };
    elems
        .into_iter()
        .map(|h| {
            vm.class_id_of_class_object(h)
                .map(|c| vm.class_desc(c).to_string())
                .unwrap_or_default()
        })
        .collect()
}

