/// Write a `jlong` instance field by name (superclass chain included).
pub(crate) fn set_long_field(vm: &mut Vm, obj: Handle, name: &str, value: i64) {
    if let Some(class) = vm.class_of_object(obj) {
        let mut c = Some(class);
        while let Some(cur) = c {
            let off = vm.classes[cur as usize]
                .declared_instance_fields
                .iter()
                .find(|f| f.name == name)
                .map(|f| f.offset as usize);
            if let Some(off) = off {
                if let Some(Object::Instance { fields, .. }) = vm.heap.get_mut(obj) {
                    if off + 1 < fields.len() {
                        let v = value as u64;
                        fields[off] = v as u32;
                        fields[off + 1] = (v >> 32) as u32;
                    }
                }
                return;
            }
            c = vm.classes[cur as usize].super_class;
        }
    }
}

/// Read a `jlong` instance field by name.
pub(crate) fn get_long_field(vm: &Vm, obj: Handle, name: &str) -> Option<i64> {
    let class = vm.class_of_object(obj)?;
    let mut c = Some(class);
    while let Some(cur) = c {
        let off = vm.classes[cur as usize]
            .declared_instance_fields
            .iter()
            .find(|f| f.name == name)
            .map(|f| f.offset as usize);
        if let Some(off) = off {
            if let Some(Object::Instance { fields, .. }) = vm.heap.get(obj) {
                let lo = *fields.get(off)? as u64;
                let hi = *fields.get(off + 1)? as u64;
                return Some((lo | (hi << 32)) as i64);
            }
            return None;
        }
        c = vm.classes[cur as usize].super_class;
    }
    None
}

/// The ACOS method id a `Method`/`Constructor` mirror carries in `artMethod`.
pub(crate) fn mirror_method_id(vm: &Vm, obj: Handle) -> Option<MethodId> {
    let mid = get_long_field(vm, obj, "artMethod").unwrap_or(0);
    if mid > 0 && (mid as usize) < vm.methods.len() {
        Some(mid as MethodId)
    } else {
        None
    }
}

/// Materialise a `java.lang.reflect.Method` mirror for `(cid, mid)`.
pub(crate) fn make_method(vm: &mut Vm, cid: ClassId, mid: MethodId) -> VmResult<Handle> {
    make_executable(vm, "Ljava/lang/reflect/Method;", cid, mid)
}

/// Materialise a `java.lang.reflect.Constructor` mirror for `(cid, mid)`.
pub(crate) fn make_constructor(vm: &mut Vm, cid: ClassId, mid: MethodId) -> VmResult<Handle> {
    make_executable(vm, "Ljava/lang/reflect/Constructor;", cid, mid)
}

fn make_executable(vm: &mut Vm, desc: &str, cid: ClassId, mid: MethodId) -> VmResult<Handle> {
    let cls = vm.load_class(desc)?;
    let obj = vm.alloc_instance(cls)?;
    vm.native_roots.push(obj);
    let result = (|| -> VmResult<()> {
        let dc = vm.class_object(cid)?;
        vm.native_roots.push(dc);
        let access = vm.methods[mid as usize].access;
        vm.set_instance_field_by_name(obj, "declaringClass", dc);
        vm.set_instance_field_by_name(obj, "accessFlags", access);
        vm.set_instance_field_by_name(obj, "dexMethodIndex", mid);
        set_long_field(vm, obj, "artMethod", mid as i64);
        vm.native_roots.pop();
        Ok(())
    })();
    vm.native_roots.pop();
    result?;
    Ok(obj)
}

fn make_ref_array(vm: &mut Vm, elem_desc: &str, elems: Vec<Handle>) -> VmResult<Handle> {
    vm.alloc(Object::Array(ArrayObj {
        elem_desc: elem_desc.to_string(),
        data: ArrayData::Ref(elems),
    }))
}

