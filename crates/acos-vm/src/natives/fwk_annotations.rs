//! DEX annotation reflection: `java.lang.Class`, `java.lang.reflect.Field`,
//! `Executable` and `Method` annotation natives, plus the `Method` /
//! `Constructor` mirror surface the annotation machinery needs.
//!
//! Real ART decodes the `annotations_directory_item` attached to each class,
//! field, method and parameter and materialises a `java.lang.reflect.Proxy`
//! whose `InvocationHandler` is `libcore.reflect.AnnotationFactory`. ACOS does
//! the same: this module decodes the already-parsed annotation structures in
//! `acos-dex` into `libcore.reflect.AnnotationMember[]` and calls the real
//! `AnnotationFactory.createAnnotation(Class, AnnotationMember[])`, so
//! `toString`/`equals`/`hashCode`/`annotationType` are exactly ART's.
//!
//! The `Proxy` class itself is generated by `natives::fwk_proxy`.

