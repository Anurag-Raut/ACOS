/// The `(dex, class_def_idx)` of a DEX-backed class.
fn class_dex_def(vm: &Vm, cid: ClassId) -> Option<(u32, usize)> {
    let c = &vm.classes[cid as usize];
    Some((c.dex?, c.def_idx?))
}

fn annotations_of_class(vm: &Vm, cid: ClassId) -> Vec<Annotation> {
    let Some((dex, def_idx)) = class_dex_def(vm, cid) else {
        return Vec::new();
    };
    let file = &vm.dexs[dex as usize].file;
    let Some(def) = file.class_defs().get(def_idx) else {
        return Vec::new();
    };
    file.annotations(def)
        .map(|d| d.class_annotations.clone())
        .unwrap_or_default()
}

fn annotations_of_field(vm: &Vm, cid: ClassId, name: &str) -> Vec<Annotation> {
    let Some((dex, def_idx)) = class_dex_def(vm, cid) else {
        return Vec::new();
    };
    let file = &vm.dexs[dex as usize].file;
    let Some(def) = file.class_defs().get(def_idx) else {
        return Vec::new();
    };
    let Some(dir) = file.annotations(def) else {
        return Vec::new();
    };
    for (fidx, anns) in &dir.field_annotations {
        if let Ok(fr) = file.field_ref(*fidx) {
            if fr.name == name {
                return anns.clone();
            }
        }
    }
    Vec::new()
}

/// Annotations on a DEX method, keyed by the DEX `method_idx`.
fn annotations_of_method(vm: &Vm, cid: ClassId, method_idx: u32) -> Vec<Annotation> {
    let Some((dex, def_idx)) = class_dex_def(vm, cid) else {
        return Vec::new();
    };
    let file = &vm.dexs[dex as usize].file;
    let Some(def) = file.class_defs().get(def_idx) else {
        return Vec::new();
    };
    let Some(dir) = file.annotations(def) else {
        return Vec::new();
    };
    for (midx, anns) in &dir.method_annotations {
        if *midx == method_idx {
            return anns.clone();
        }
    }
    Vec::new()
}

fn parameter_annotations_of_method(vm: &Vm, cid: ClassId, method_idx: u32) -> Vec<Vec<Annotation>> {
    let Some((dex, def_idx)) = class_dex_def(vm, cid) else {
        return Vec::new();
    };
    let file = &vm.dexs[dex as usize].file;
    let Some(def) = file.class_defs().get(def_idx) else {
        return Vec::new();
    };
    let Some(dir) = file.annotations(def) else {
        return Vec::new();
    };
    for (midx, sets) in &dir.parameter_annotations {
        if *midx == method_idx {
            return sets.clone();
        }
    }
    Vec::new()
}

/// The DEX `(dex, method_idx)` behind an ACOS method id, if DEX-backed.
fn dex_method(vm: &Vm, mid: MethodId) -> Option<(u32, u32)> {
    match &vm.methods[mid as usize].imp {
        crate::class::MethodImpl::Dex {
            dex, method_idx, ..
        } => Some((*dex, *method_idx)),
        _ => None,
    }
}

fn find_annotation(anns: &[Annotation], file: &DexFile, desc: &str, vis: u8) -> Option<Annotation> {
    anns.iter()
        .find(|a| {
            a.visibility == vis
                && file
                    .type_descriptor(a.type_idx())
                    .map(|d| d == desc)
                    .unwrap_or(false)
        })
        .cloned()
}

