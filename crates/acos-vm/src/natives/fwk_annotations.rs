/// Build the `Annotation` object for one runtime annotation using the real
/// `libcore.reflect.AnnotationFactory`.
fn make_annotation(
    vm: &mut Vm,
    file: &Arc<DexFile>,
    ann_cid: ClassId,
    ann: &Annotation,
) -> VmResult<Handle> {
    let base = vm.native_roots.len();
    let member_cid = vm.load_class(ANNOTATION_MEMBER)?;
    let factory_cid = vm.load_class(ANNOTATION_FACTORY)?;
    let ann_class_obj = vm.class_object(ann_cid)?;
    vm.native_roots.push(ann_class_obj);

    let mut members: Vec<Handle> = Vec::new();
    for elem in ann.elements() {
        let name = file.string(elem.name_idx)?.to_string();
        // The element's declared type is the annotation interface method's
        // return type; its `Method` mirror is what `AnnotationFactory` compares
        // the proxy method against.
        let Some((imid, ret_desc)) = find_annotation_method(vm, ann_cid, &name) else {
            continue;
        };
        let method_h = make_method(vm, ann_cid, imid)?;
        vm.native_roots.push(method_h);
        let type_cid = vm.load_class(&ret_desc)?;
        let type_h = vm.class_object(type_cid)?;
        vm.native_roots.push(type_h);
        let value_h = decode_value(vm, file, &elem.value, &ret_desc)?;
        vm.native_roots.push(value_h);
        let name_h = vm.new_string(&name)?;
        vm.native_roots.push(name_h);

        let obj = vm.alloc_instance(member_cid)?;
        vm.native_roots.push(obj);
        let ctor = vm.find_method(
            member_cid,
            "<init>",
            "(Ljava/lang/String;Ljava/lang/Object;Ljava/lang/Class;Ljava/lang/reflect/Method;)V",
            InvokeKind::Direct,
        )?;
        crate::interp::call_method(
            vm,
            ctor,
            obj,
            &[
                name_h as u64,
                value_h as u64,
                type_h as u64,
                method_h as u64,
            ],
        )?;
        members.push(obj);
    }

    let member_arr = make_ref_array(vm, ANNOTATION_MEMBER, members)?;
    vm.native_roots.push(member_arr);
    let create = vm.find_method(
        factory_cid,
        "createAnnotation",
        "(Ljava/lang/Class;[Llibcore/reflect/AnnotationMember;)Ljava/lang/annotation/Annotation;",
        InvokeKind::Static,
    )?;
    let result =
        crate::interp::call_method(vm, create, NULL, &[ann_class_obj as u64, member_arr as u64]);
    vm.native_roots.truncate(base);
    Ok(result? as u32)
}

/// Find the annotation-interface method `name()` and its return descriptor.
fn find_annotation_method(vm: &Vm, ann_cid: ClassId, name: &str) -> Option<(MethodId, String)> {
    let declared = &vm.classes[ann_cid as usize].declared_methods;
    for &mid in declared {
        let m = &vm.methods[mid as usize];
        if m.name == name && m.params.is_empty() {
            return Some((mid, vm.type_desc(m.ret).to_string()));
        }
    }
    for &sup in &vm.classes[ann_cid as usize].interfaces {
        if let Some(v) = find_annotation_method(vm, sup, name) {
            return Some(v);
        }
    }
    None
}

/// Materialise every annotation of the requested visibility as an array.
fn materialise_all(
    vm: &mut Vm,
    file: &Arc<DexFile>,
    anns: &[Annotation],
    vis: u8,
) -> VmResult<Handle> {
    let base = vm.native_roots.len();
    let mut elems = Vec::new();
    for ann in anns {
        if ann.visibility != vis {
            continue;
        }
        let desc = file.type_descriptor(ann.type_idx())?.to_string();
        let Ok(ann_cid) = vm.load_class(&desc) else {
            continue;
        };
        let h = make_annotation(vm, file, ann_cid, ann)?;
        vm.native_roots.push(h);
        elems.push(h);
    }
    let arr = make_ref_array(vm, "Ljava/lang/annotation/Annotation;", elems)?;
    vm.native_roots.truncate(base);
    Ok(arr)
}

/// Decode the `@Signature` system annotation into a `String[]`.
fn signature_value(vm: &mut Vm, file: &Arc<DexFile>, anns: &[Annotation]) -> VmResult<Handle> {
    let Some(ann) = find_annotation(anns, file, SIGNATURE_ANNOTATION, VISIBILITY_SYSTEM)
        .or_else(|| find_annotation(anns, file, SIGNATURE_ANNOTATION, VISIBILITY_RUNTIME))
    else {
        return Ok(NULL);
    };
    let Some(elem) = ann.elements().first() else {
        return Ok(NULL);
    };
    decode_value(vm, file, &elem.value, "[Ljava/lang/String;")
}

