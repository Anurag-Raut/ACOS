//! `derive_layouts` — decode every WMS parcelable's `writeToParcel` out of the
//! Android 14 boot DEX and emit `results/wm/parcelable_layouts.txt`.
//!
//! This is the evidence behind `src/codec.rs`: the field order in each codec is
//! the `iget` → `Parcel.write*` sequence printed here. It uses `acos-dex`
//! directly (a dev-dependency, so the runtime crate stays VM/DEX-free).
//!
//! ```text
//! cargo run -p acos-wm --example derive_layouts
//! ```

use std::fmt::Write as _;
use std::path::PathBuf;
use std::sync::Arc;

use acos_dex::{disasm::disassemble, DexFile};

/// `(class descriptor, method name)` pairs whose layouts `codec.rs` implements.
const TARGETS: &[(&str, &str)] = &[
    ("Landroid/graphics/Rect;", "writeToParcel"),
    ("Landroid/graphics/Point;", "writeToParcel"),
    ("Landroid/graphics/Insets;", "writeToParcel"),
    ("Landroid/os/LocaleList;", "writeToParcel"),
    ("Landroid/text/TextUtils;", "writeToParcel"),
    ("Landroid/app/WindowConfiguration;", "writeToParcel"),
    ("Landroid/content/res/Configuration;", "writeToParcel"),
    ("Landroid/util/MergedConfiguration;", "writeToParcel"),
    ("Landroid/window/ClientWindowFrames;", "writeToParcel"),
    ("Landroid/view/SurfaceControl;", "writeToParcel"),
    (
        "Landroid/view/DisplayCutout$ParcelableWrapper;",
        "writeCutoutToParcel",
    ),
    ("Landroid/view/RoundedCorner;", "writeToParcel"),
    ("Landroid/view/RoundedCorners;", "writeToParcel"),
    ("Landroid/view/PrivacyIndicatorBounds;", "writeToParcel"),
    ("Landroid/view/DisplayShape;", "writeToParcel"),
    ("Landroid/view/InsetsSource;", "writeToParcel"),
    ("Landroid/view/InsetsSourceControl;", "writeToParcel"),
    ("Landroid/view/InsetsSourceControl$Array;", "writeToParcel"),
    ("Landroid/view/InsetsState;", "writeToParcel"),
    ("Landroid/view/InsetsFrameProvider;", "writeToParcel"),
    ("Landroid/view/WindowManager$LayoutParams;", "writeToParcel"),
    ("Landroid/view/InputChannel;", "writeToParcel"),
    ("Landroid/view/inputmethod/EditorInfo;", "writeToParcel"),
    (
        "Lcom/android/internal/inputmethod/InputBindResult;",
        "writeToParcel",
    ),
    (
        "Lcom/android/internal/inputmethod/InputConnectionCommandHeader;",
        "writeToParcel",
    ),
];

fn workspace_root() -> PathBuf {
    let crate_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    crate_dir
        .parent()
        .and_then(std::path::Path::parent)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("."))
}

fn proto(dex: &DexFile, idx: u32) -> String {
    match dex.proto(idx) {
        Ok(p) => {
            let mut s = String::from("(");
            for &t in &p.parameters {
                if let Ok(d) = dex.type_descriptor(t) {
                    s.push_str(d);
                }
            }
            s.push(')');
            if let Ok(d) = dex.type_descriptor(p.return_type_idx) {
                s.push_str(d);
            }
            s
        }
        Err(_) => "()?".into(),
    }
}

/// True for a line that records a layout-affecting operation.
fn is_layout_line(line: &str) -> bool {
    line.contains("iget")
        || line.contains("Parcel;.write")
        || line.contains("Parcel;.read")
        || line.contains("Parcel;.create")
        || line.contains("TextUtils;.writeToParcel")
        || line.contains("nativeWrite")
        || line.contains("UserHandle;.writeToParcel")
        || line.contains("writeTypedObject")
        || line.contains("writeTypedArray")
}

fn main() {
    let root = workspace_root();
    let dex_dir = root.join(".cache/boot/android-34/dex/framework");
    let out_dir = root.join("results/wm");
    std::fs::create_dir_all(&out_dir).expect("create results/wm");

    let mut dexes = Vec::new();
    for name in [
        "classes.dex",
        "classes2.dex",
        "classes3.dex",
        "classes4.dex",
        "classes5.dex",
    ] {
        let path = dex_dir.join(name);
        match std::fs::read(&path) {
            Ok(data) => match DexFile::parse(Arc::<[u8]>::from(data)) {
                Ok(d) => dexes.push(d),
                Err(e) => eprintln!("parse {}: {e}", path.display()),
            },
            Err(e) => eprintln!("read {}: {e}", path.display()),
        }
    }

    let mut out = String::new();
    out.push_str("# WMS parcelable layouts, mechanically decoded\n\n");
    out.push_str("Generated by `cargo run -p acos-wm --example derive_layouts` from\n");
    out.push_str("`.cache/boot/android-34/dex/framework/classes{1..5}.dex`.\n\n");
    out.push_str("Each block is the ordered `iget <field>` / `Parcel.write*` sequence of the\n");
    out.push_str("class's own `writeToParcel`; `src/codec.rs` transcribes it. Addresses are DEX\n");
    out.push_str("code-unit offsets.\n\n");

    let mut found = 0usize;
    for (class, method) in TARGETS {
        for dex in &dexes {
            let Some(def) = dex.find_class(class) else {
                continue;
            };
            let Ok(Some(cd)) = dex.class_data(def) else {
                continue;
            };
            for em in cd.direct_methods.iter().chain(cd.virtual_methods.iter()) {
                let Ok(r) = dex.method_ref(em.method_idx) else {
                    continue;
                };
                if r.name != *method {
                    continue;
                }
                found += 1;
                let _ = writeln!(out, "## {class}->{method}{}", proto(dex, r.proto_idx));
                let _ = writeln!(out, "```text");
                if em.code_off == 0 {
                    let _ = writeln!(out, "(abstract/native)");
                } else if let Ok(code) = dex.code_item(em.code_off) {
                    if let Ok(insns) = disassemble(dex, &code) {
                        for (pc, line) in &insns {
                            if is_layout_line(line) {
                                let _ = writeln!(out, "{pc:04x}: {line}");
                            }
                        }
                    }
                }
                let _ = writeln!(out, "```\n");
            }
        }
    }

    if found != TARGETS.len() {
        eprintln!(
            "warning: decoded {found}/{} targets (some classes are absent from the boot dex set)",
            TARGETS.len()
        );
    }

    let path = out_dir.join("parcelable_layouts.txt");
    std::fs::write(&path, &out).expect("write parcelable_layouts.txt");
    println!(
        "wrote {} ({} bytes, {} targets)",
        path.display(),
        out.len(),
        found
    );
}
