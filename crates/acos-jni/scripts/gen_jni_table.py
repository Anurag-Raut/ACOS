#!/usr/bin/env python3
"""Generate `src/table.rs` and `src/traps.rs` for `acos-jni`.

`jni_slots.txt` is the field order of `struct JNINativeInterface` in the NDK's
`jni.h` (API 34 / NDK 27.1). The generated table must match it exactly: guest
code indexes it through `(*env)->Slot(...)`.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SLOTS = os.path.join(ROOT, "src", "jni_slots.txt")
TABLE_OUT = os.path.join(ROOT, "src", "table.rs")
TRAPS_OUT = os.path.join(ROOT, "src", "traps.rs")

# Slots implemented as Rust `extern "C" fn jni_<Slot>` in src/jni.rs.
RUST_IMPL = {
    "GetVersion", "FindClass", "GetSuperclass", "IsAssignableFrom",
    "Throw", "ThrowNew", "ExceptionOccurred", "ExceptionDescribe",
    "ExceptionClear", "ExceptionCheck", "PushLocalFrame", "PopLocalFrame",
    "NewGlobalRef", "DeleteGlobalRef", "DeleteLocalRef", "IsSameObject",
    "NewLocalRef", "EnsureLocalCapacity", "AllocObject", "GetObjectClass",
    "IsInstanceOf", "GetMethodID", "GetStaticMethodID",
    "GetFieldID", "GetStaticFieldID",
    "GetObjectField", "GetBooleanField", "GetByteField", "GetCharField",
    "GetShortField", "GetIntField", "GetLongField", "GetFloatField",
    "GetDoubleField",
    "SetObjectField", "SetBooleanField", "SetByteField", "SetCharField",
    "SetShortField", "SetIntField", "SetLongField", "SetFloatField",
    "SetDoubleField",
    "GetStaticObjectField", "GetStaticBooleanField", "GetStaticByteField",
    "GetStaticCharField", "GetStaticShortField", "GetStaticIntField",
    "GetStaticLongField", "GetStaticFloatField", "GetStaticDoubleField",
    "SetStaticObjectField", "SetStaticBooleanField", "SetStaticByteField",
    "SetStaticCharField", "SetStaticShortField", "SetStaticIntField",
    "SetStaticLongField", "SetStaticFloatField", "SetStaticDoubleField",
    "NewString", "GetStringLength", "GetStringChars", "ReleaseStringChars",
    "GetStringRegion", "NewStringUTF", "GetStringUTFLength",
    "GetStringUTFChars", "ReleaseStringUTFChars", "GetStringUTFRegion",
    "GetArrayLength",
    "NewBooleanArray", "NewByteArray", "NewCharArray", "NewShortArray",
    "NewIntArray", "NewLongArray", "NewFloatArray", "NewDoubleArray",
    "NewObjectArray",
    "GetBooleanArrayElements", "GetByteArrayElements", "GetCharArrayElements",
    "GetShortArrayElements", "GetIntArrayElements", "GetLongArrayElements",
    "GetFloatArrayElements", "GetDoubleArrayElements",
    "ReleaseBooleanArrayElements", "ReleaseByteArrayElements",
    "ReleaseCharArrayElements", "ReleaseShortArrayElements",
    "ReleaseIntArrayElements", "ReleaseLongArrayElements",
    "ReleaseFloatArrayElements", "ReleaseDoubleArrayElements",
    "GetBooleanArrayRegion", "GetByteArrayRegion", "GetCharArrayRegion",
    "GetShortArrayRegion", "GetIntArrayRegion", "GetLongArrayRegion",
    "GetFloatArrayRegion", "GetDoubleArrayRegion",
    "SetBooleanArrayRegion", "SetByteArrayRegion", "SetCharArrayRegion",
    "SetShortArrayRegion", "SetIntArrayRegion", "SetLongArrayRegion",
    "SetFloatArrayRegion", "SetDoubleArrayRegion",
    "GetObjectArrayElement", "SetObjectArrayElement",
    "GetPrimitiveArrayCritical", "ReleasePrimitiveArrayCritical",
    "RegisterNatives", "UnregisterNatives", "GetJavaVM",
    "MonitorEnter", "MonitorExit", "GetObjectRefType",
    "GetStringCritical", "ReleaseStringCritical",
    "NewWeakGlobalRef", "DeleteWeakGlobalRef",
    "NewDirectByteBuffer", "GetDirectBufferAddress", "GetDirectBufferCapacity",
}

# Slots implemented in the C varargs trampoline (csrc/jni_varargs.c).
CALL_TYPES = [
    "Object", "Boolean", "Byte", "Char", "Short", "Int", "Long",
    "Float", "Double", "Void",
]
C_IMPL = set()
for t in CALL_TYPES:
    for form in ("", "V", "A"):
        C_IMPL.add(f"Call{t}Method{form}")
        C_IMPL.add(f"CallStatic{t}Method{form}")
        C_IMPL.add(f"CallNonvirtual{t}Method{form}")
for form in ("", "V", "A"):
    C_IMPL.add(f"NewObject{form}")

INVOKE = [
    "DestroyJavaVM", "AttachCurrentThread", "DetachCurrentThread",
    "GetEnv", "AttachCurrentThreadAsDaemon",
]


def main() -> int:
    with open(SLOTS, "r", encoding="utf-8") as fh:
        slots = [line.strip() for line in fh if line.strip()]
    if len(slots) != 229:
        print(f"expected 229 slots, found {len(slots)}", file=sys.stderr)
        return 1
    missing = RUST_IMPL | C_IMPL
    unknown = sorted(missing - set(slots))
    if unknown:
        print(f"implemented slots not in the JNI list: {unknown}", file=sys.stderr)
        return 1

    reserved = ["reserved0", "reserved1", "reserved2", "reserved3"]
    all_slots = reserved + slots
    lines = [
        "// @generated by scripts/gen_jni_table.py -- do not edit by hand.",
        "//! JNI function tables in exact `struct JNINativeInterface` order.",
        "#![allow(non_snake_case, clippy::too_many_arguments)]",
        "",
        "use std::sync::OnceLock;",
        "",
        "extern \"C\" {",
    ]
    for name in sorted(C_IMPL):
        lines.append(f"    pub fn acosrjni_{name}();")
    lines += [
        "}",
        "",
        f"/// Number of entries in the C table (4 reserved + {len(slots)}).",
        f"pub const JNI_SLOT_COUNT: usize = {len(all_slots)};",
        "",
        "/// Slot names, index-aligned with the function table.",
        "pub const JNI_SLOT_NAMES: [&str; JNI_SLOT_COUNT] = [",
    ]
    for name in all_slots:
        lines.append(f"    \"{name}\",")
    lines += [
        "];",
        "",
        "static NATIVE_TABLE: OnceLock<Box<[usize; JNI_SLOT_COUNT]>> = OnceLock::new();",
        "static INVOKE_TABLE: OnceLock<Box<[usize; 8]>> = OnceLock::new();",
        "",
        "/// `JNINativeInterface*` (point to the first slot, not the reserved ones).",
        "pub fn native_table_ptr() -> *const usize {",
        "    let t = NATIVE_TABLE.get_or_init(|| Box::new(build_native_table()));",
        "    t.as_ptr()",
        "}",
        "",
        "/// `JNIInvokeInterface*`.",
        "pub fn invoke_table_ptr() -> *const usize {",
        "    let t = INVOKE_TABLE.get_or_init(|| Box::new(build_invoke_table()));",
        "    t.as_ptr()",
        "}",
        "",
        "fn build_native_table() -> [usize; JNI_SLOT_COUNT] {",
        "    [",
    ]
    for name in reserved:
        lines.append(f"        0, // {name}")
    for name in slots:
        if name in RUST_IMPL:
            lines.append(f"        crate::jni::jni_{name} as *const () as usize,")
        elif name in C_IMPL:
            lines.append(f"        acosrjni_{name} as *const () as usize,")
        else:
            lines.append(f"        crate::traps::trap_{name} as *const () as usize,")
    lines += [
        "    ]",
        "}",
        "",
        "fn build_invoke_table() -> [usize; 8] {",
        "    [",
        "        0, 0, 0,",
    ]
    for name in INVOKE:
        lines.append(f"        crate::jni::vm_{name} as *const () as usize,")
    lines += ["    ]", "}", ""]

    with open(TABLE_OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    trap_lines = [
        "// @generated by scripts/gen_jni_table.py -- do not edit by hand.",
        "//! One structured trap per unimplemented JNI slot.",
        "//!",
        "//! The trap records `JNI_UNSUPPORTED` in the calling thread and returns the",
        "//! slot's zero value; the enclosing native call is then aborted with the",
        "//! structured error. It never aborts the host process and never guesses.",
        "#![allow(non_snake_case, clippy::too_many_arguments)]",
        "",
    ]
    for name in slots:
        if name in RUST_IMPL or name in C_IMPL:
            continue
        trap_lines.append(
            "pub unsafe extern \"C\" fn trap_" + name +
            "(_a: usize, _b: usize, _c: usize, _d: usize, "
            "_e: usize, _f: usize, _g: usize, _h: usize) -> usize { "
            "crate::jni::unsupported(\"" + name + "\"); 0 }"
        )
    trap_lines.append("")
    with open(TRAPS_OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(trap_lines))

    print(f"wrote {TABLE_OUT} ({len(all_slots)} slots) and {TRAPS_OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
