#!/usr/bin/env python3
"""Generate src/testjni/table_gen.rs from src/testjni/jni_slots.txt.

The slot list is the field order of `struct JNINativeInterface` in the NDK's
`jni.h` (API 34 / NDK 27.1). The generated table must match that order exactly:
the guest indexes it through `(*env)->Slot(...)`.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SLOTS = os.path.join(ROOT, "src", "testjni", "jni_slots.txt")
OUT = os.path.join(ROOT, "src", "testjni", "table_gen.rs")
TRAPS_OUT = os.path.join(ROOT, "src", "testjni", "traps_gen.rs")

# Slots implemented in Rust (`super::jni_impl::jni_<Name>`).
RUST_IMPL = {
    "GetVersion", "FindClass", "GetMethodID", "GetStaticMethodID",
    "GetObjectClass", "CallStaticIntMethodA", "CallStaticVoidMethodA",
    "CallVoidMethodA", "CallIntMethodA", "CallStaticObjectMethodA",
    "CallObjectMethodA", "NewStringUTF", "GetStringUTFChars",
    "ReleaseStringUTFChars", "GetArrayLength", "GetIntArrayElements",
    "ReleaseIntArrayElements", "GetIntArrayRegion", "SetIntArrayRegion",
    "RegisterNatives", "ThrowNew", "ExceptionCheck", "ExceptionOccurred",
    "ExceptionClear", "DeleteLocalRef", "GetJavaVM",
}

# Slots implemented in the C varargs shim (`extern "C"` symbol).
C_IMPL = {
    "CallStaticIntMethod", "CallStaticIntMethodV",
    "CallStaticVoidMethod", "CallStaticVoidMethodV",
    "CallStaticObjectMethod", "CallStaticObjectMethodV",
    "CallStaticBooleanMethod", "CallStaticBooleanMethodV",
    "CallIntMethod", "CallIntMethodV",
    "CallVoidMethod", "CallVoidMethodV",
    "CallObjectMethod", "CallObjectMethodV",
    "CallBooleanMethod", "CallBooleanMethodV",
}

INVOKE = [
    "DestroyJavaVM", "AttachCurrentThread", "DetachCurrentThread",
    "GetEnv", "AttachCurrentThreadAsDaemon",
]


def main() -> int:
    with open(SLOTS, "r", encoding="utf-8") as fh:
        slots = [line.strip() for line in fh if line.strip()]
    if len(slots) != 229:
        print(f"expected 229 slots, found {len(slots)}", file=sys.stderr)
        return 1

    lines = []
    lines.append("// @generated by scripts/gen_jni_table.py -- do not edit by hand.")
    lines.append("//! JNI function tables in exact `struct JNINativeInterface` order.")
    lines.append("#![allow(non_snake_case, clippy::too_many_arguments)]")
    lines.append("")
    lines.append("extern \"C\" {")
    for name in sorted(C_IMPL):
        lines.append(f"    pub fn acos_jni_{name}();")
    lines.append("}")
    lines.append("")
    # The C struct begins with four reserved pointer slots before GetVersion.
    reserved = ["reserved0", "reserved1", "reserved2", "reserved3"]
    all_slots = reserved + slots
    lines.append("/// Number of slots in the C `JNINativeInterface` table (4 reserved + 229).")
    lines.append(f"pub const JNI_SLOT_COUNT: usize = {len(all_slots)};")
    lines.append("")
    lines.append("/// Slot names, index-aligned with the function table.")
    lines.append("pub const JNI_SLOT_NAMES: [&str; JNI_SLOT_COUNT] = [")
    for name in all_slots:
        lines.append(f"    \"{name}\",")
    lines.append("];")
    lines.append("")
    lines.append("/// Build the `JNINativeInterface` function-pointer table.")
    lines.append("pub fn native_interface_table() -> [usize; JNI_SLOT_COUNT] {")
    lines.append("    [")
    for name in reserved:
        lines.append("        0, // " + name)
    for name in slots:
        if name in RUST_IMPL:
            lines.append(f"        super::jni_impl::jni_{name} as *const () as usize,")
        elif name in C_IMPL:
            lines.append(f"        acos_jni_{name} as *const () as usize,")
        else:
            lines.append(f"        super::traps_gen::trap_{name} as *const () as usize,")
    lines.append("    ]")
    lines.append("}")
    lines.append("")
    lines.append("/// Build the `JNIInvokeInterface` table (3 reserved + 5 functions).")
    lines.append("pub fn invoke_interface_table() -> [usize; 8] {")
    lines.append("    [")
    lines.append("        0, 0, 0,")
    for name in INVOKE:
        lines.append(f"        super::jni_impl::vm_{name} as *const () as usize,")
    lines.append("    ]")
    lines.append("}")
    lines.append("")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    # Distinct trap function per unimplemented slot.
    trap_lines = []
    trap_lines.append("// @generated by scripts/gen_jni_table.py -- do not edit by hand.")
    trap_lines.append("//! One distinct aborting trap per unimplemented JNI slot. Generating a")
    trap_lines.append("//! function per slot (rather than sharing one) lets the trap name the exact")
    trap_lines.append("//! slot that was called.")
    trap_lines.append("#![allow(non_snake_case, clippy::too_many_arguments)]")
    trap_lines.append("")
    trap_lines.append("fn report_and_abort(name: &str) -> ! {")
    trap_lines.append("    eprintln!(\"acos test JNI trap: unimplemented JNI slot called: {name}\");")
    trap_lines.append("    std::process::abort();")
    trap_lines.append("}")
    trap_lines.append("")
    for name in slots:
        if name in RUST_IMPL or name in C_IMPL:
            continue
        trap_lines.append(
            "pub unsafe extern \"C\" fn trap_" + name +
            "(_a: usize, _b: usize, _c: usize, _d: usize, "
            "_e: usize, _f: usize, _g: usize, _h: usize) -> usize "
            "{ report_and_abort(\"" + name + "\") }"
        )
    trap_lines.append("")
    with open(TRAPS_OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(trap_lines))

    print(f"wrote {OUT} ({len(all_slots)} slots) and {TRAPS_OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
