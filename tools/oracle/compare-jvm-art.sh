#!/usr/bin/env bash
#
# compare-jvm-art.sh — diff the weak `jvm-reference` expectations
# (fixtures/expected/, host OpenJDK 17) against the authoritative
# `art-reference` outputs (fixtures/expected-art/, real ART on API 34).
#
# Writes results/oracle/jvm-vs-art.md: a per-program verdict (identical /
# differs) plus the exact differing lines, so the differences that define where
# the JVM oracle is WRONG for Android are explicit and auditable.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
JVM_DIR="$ROOT/fixtures/expected/dexprogs"
ART_DIR="$ROOT/fixtures/expected-art/dexprogs"
OUT="$ROOT/results/oracle/jvm-vs-art.md"

[ -d "$JVM_DIR" ] || { echo "compare-jvm-art: missing $JVM_DIR" >&2; exit 1; }
[ -d "$ART_DIR" ] || { echo "compare-jvm-art: missing $ART_DIR (run run-dexprogs-art.sh)" >&2; exit 1; }

mkdir -p "$(dirname "$OUT")"
tmplog="$(mktemp)"
trap 'rm -f "$tmplog"' EXIT

identical=0
differ=0
{
    echo "# JVM reference vs real ART (API 34, x86_64)"
    echo
    echo "- **JVM side:** \`fixtures/expected/dexprogs/\` — host OpenJDK 17,"
    echo "  fidelity label **jvm-reference** (weak)."
    echo "- **ART side:** \`fixtures/expected-art/dexprogs/\` — real ART via"
    echo "  \`dalvikvm64 -cp classes.dex Main\` on the API-34 google_apis x86_64"
    echo "  emulator under KVM, fidelity label **art-reference** (authoritative)."
    echo "- Generated by \`tools/oracle/compare-jvm-art.sh\`."
    echo
    echo "A JVM match is never Android-verified; every \`differs\` line below is a"
    echo "place where the JVM oracle is **wrong** for Android and the ART output is"
    echo "the one ACOS must match."
    echo
    echo "## Verdict table"
    echo
    echo "| program | stdout | exit | stderr | verdict |"
    echo "|---|---|---|---|---|"
} >"$OUT"

for art_stdout in "$ART_DIR"/*.stdout; do
    [ -f "$art_stdout" ] || continue
    name="$(basename "$art_stdout" .stdout)"
    jvm_stdout="$JVM_DIR/$name.stdout"
    art_stderr="$ART_DIR/$name.stderr"
    jvm_stderr="$JVM_DIR/$name.stderr"
    art_exit="$(tr -d '\r\n' <"$ART_DIR/$name.exit" 2>/dev/null || echo '?')"
    jvm_exit="$(tr -d '\r\n' <"$JVM_DIR/$name.exit" 2>/dev/null || echo '?')"

    [ -f "$jvm_stdout" ] || { echo "compare-jvm-art: missing $jvm_stdout" >&2; exit 1; }

    stdout_v="identical"
    if ! cmp -s "$jvm_stdout" "$art_stdout"; then
        stdout_v="differs"
    fi
    exit_v="identical"
    [ "$jvm_exit" != "$art_exit" ] && exit_v="differs"

    # stderr: JVM records only the first line for expected-failure programs.
    stderr_v="identical"
    if [ -f "$jvm_stderr" ]; then
        jvm_first="$(head -n 1 "$jvm_stderr")"
        art_first="$(head -n 1 "$art_stderr" 2>/dev/null || true)"
        stderr_v="differs"
        if [ "$jvm_first" = "$art_first" ] && [ "$(wc -l <"$art_stderr")" -le 1 ]; then
            stderr_v="identical"
        fi
    else
        if [ -s "$art_stderr" ]; then
            stderr_v="differs"
        fi
    fi

    overall="identical"
    if [ "$stdout_v" != identical ] || [ "$exit_v" != identical ] || [ "$stderr_v" != identical ]; then
        overall="**differs**"
        differ=$((differ + 1))
    else
        identical=$((identical + 1))
    fi
    {
        printf '| %s | %s | %s | %s | %s |\n' "$name" "$stdout_v" "$exit_v" "$stderr_v" "$overall"
    } >>"$OUT"

    if [ "$overall" = "**differs**" ]; then
        {
            echo
            echo "### $name"
            echo
            if [ "$exit_v" != identical ]; then
                echo "- **exit:** JVM \`$jvm_exit\` vs ART \`$art_exit\`."
            fi
            if [ "$stderr_v" != identical ]; then
                echo "- **stderr:** JVM (recorded) vs ART (full). The JVM expectation"
                echo "  records only the first line; ART emits the complete stack trace."
                echo
                echo '  ```'
                if [ -f "$jvm_stderr" ]; then
                    echo "  [JVM recorded first line] $(head -n 1 "$jvm_stderr")"
                else
                    echo "  [JVM] (empty / not recorded)"
                fi
                sed 's/^/  [ART] /' "$art_stderr"
                echo '  ```'
            fi
            if [ "$stdout_v" != identical ]; then
                echo "- **stdout diff** (\`-JVM +ART\`):"
                echo
                echo '  ```diff'
                diff -u --label "JVM/$name.stdout" --label "ART/$name.stdout" \
                    "$jvm_stdout" "$art_stdout" | tail -n +3 | sed 's/^/  /' || true
                echo '  ```'
            fi
        } >>"$OUT"
    fi
done

{
    echo
    echo "## Summary"
    echo
    echo "- identical: **$identical**"
    echo "- differs: **$differ**"
    echo
    echo "## Where the JVM oracle is wrong for Android"
    echo
    echo "The only measured divergence in this corpus is \`20_uncaught\`, and it is"
    echo "**not** a runtime-semantic difference: build-fixtures.sh records only the"
    echo "first stderr line of a failed program, while ART (like any JVM) emits the"
    echo "full stack trace. The complete ART trace is:"
    echo
    echo '```'
    echo 'Exception in thread "main" Main$Fatal: fatal without args'
    printf '\tat Main.main(Main.java:14)\n'
    echo '```'
    echo
    echo "Everything else is byte-identical on both VMs, which is a real (if narrow)"
    echo "result: for this portable subset there is **no** JVM-ART divergence in"
    echo "Float/Double printing (04), String.hashCode (09), Object.toString"
    echo "class-prefix behaviour (10), collection iteration order (17), Integer"
    echo "cache/boxing identity (17), thread-scheduling output (19), or the VM-thrown"
    echo "exception class names the fixtures print (13)."
    echo
    echo "Caveat: the fixtures were deliberately written to avoid JVM-specific message"
    echo "text and identity hashes (see fixtures/README.md); \"identical\" therefore"
    echo "means \"identical on this portable subset\", **not** \"ART == JVM for all"
    echo "Android semantics\". A jvm-reference pass still can never satisfy an"
    echo "art-reference requirement (ADR-0005); the real Android app/framework/JNI"
    echo "evidence is in fixtures/reference/."
} >>"$OUT"

# Append the non-determinism note if present.
if [ -s "$ROOT/results/oracle/dexprogs-nondeterminism.txt" ]; then
    {
        echo
        echo "Non-deterministic across 3 ART runs (see"
        echo "\`results/oracle/dexprogs-nondeterminism.txt\`):"
        echo
        sed 's/^/- /' "$ROOT/results/oracle/dexprogs-nondeterminism.txt"
    } >>"$OUT"
fi

cat "$OUT"
echo
echo "compare-jvm-art: identical=$identical differs=$differ -> $OUT"
