#!/usr/bin/env bash
#
# Build the ACOS Flutter "hello" fixture (dev.acos.fixtures.flutterhello)
# without Gradle and without the 1.5 GB Flutter SDK.
#
# It uses the official Flutter engine artifacts for the pinned engine hash
# 89c39edfdfae2949f6806e4a315c0c08522238b7 (Flutter 3.47.9 / Dart 3.13.7):
#   * flutter.jar  -> Android embedding classes + libflutter.so
#   * gen_snapshot -> AOT-compiles the Dart kernel to libapp.so
#   * flutter_patched_sdk_product -> dart:ui platform kernel for the kernel step
# plus the AndroidX closure referenced by flutter.jar (resolved read-only from
# the local Gradle module cache by tools/flutter_androidx.py).
#
# Everything downloaded lives under .cache/flutter-1/ (gitignored), in its own
# directory. No Gradle, no Flutter SDK, no privileged commands.
#
# Usage:
#   tools/build-flutter-hello.sh [x86_64|arm64]
#
# Outputs (signed + zipaligned):
#   fixtures/build/apps/flutter-hello.apk        (x86_64, default)
#   fixtures/build/apps/flutter-hello-arm64.apk  (arm64-v8a, phone reference)
#
# Rebuild prerequisites:
#   .cache/flutter-1/engine/{artifacts/flutter.jar,linux64/gen_snapshot}
#   .cache/flutter-1/engine/patched/flutter_patched_sdk_product/
#   .cache/flutter-1/engine-arm64/{artifacts/flutter.jar,linux64/gen_snapshot}
#   .cache/flutter-1/androidx.jar (generated by tools/flutter_androidx.py)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

if [ -z "${ACOS_GUARDED:-}" ]; then
    exec "$ROOT/tools/guarded.sh" --mem 6G --time 1800 -- \
        env ACOS_GUARDED=1 "$0" "$@"
fi

SDK="${ANDROID_HOME:-/home/Qui/Android/Sdk}"
BUILD_TOOLS_VERSION="${BUILD_TOOLS_VERSION:-35.0.0}"
BT="$SDK/build-tools/$BUILD_TOOLS_VERSION"
ANDROID_JAR="$SDK/platforms/android-34/android.jar"
AAPT2="$BT/aapt2"
D8="$BT/d8"
ZIPALIGN="$BT/zipalign"
APKSIGNER="$BT/apksigner"

CACHE="$ROOT/.cache/flutter-1"
APP_DIR="$ROOT/fixtures/apps/flutter-hello"
OUT_DIR="$ROOT/fixtures/build/apps"
KEYSTORE="$OUT_DIR/debug.keystore"
KEY_ALIAS="androiddebugkey"
KEY_PASS="android"
VARIANT="${1:-x86_64}"

# Keep Java's heap bounded; d8/javac are the heavy steps.
export JAVA_OPTS="${JAVA_OPTS:--Xmx2g}"

die() { echo "build-flutter-hello: error: $*" >&2; exit 1; }
log() { echo "build-flutter-hello: $*"; }

case "$VARIANT" in
    x86_64)
        ABI="x86_64"
        ENGINE="$CACHE/engine"
        GEN="$ENGINE/linux64/gen_snapshot"
        FLUTTER_JAR="$ENGINE/artifacts/flutter.jar"
        OUT="$OUT_DIR/flutter-hello.apk"
        ;;
    arm64)
        ABI="arm64-v8a"
        ENGINE="$CACHE/engine-arm64"
        GEN="$ENGINE/linux64/gen_snapshot"
        FLUTTER_JAR="$ENGINE/artifacts/flutter.jar"
        OUT="$OUT_DIR/flutter-hello-arm64.apk"
        ;;
    *)
        die "unknown variant: $VARIANT (use x86_64 or arm64)"
        ;;
esac

command -v javac >/dev/null 2>&1 || die "javac not found on PATH"
command -v python3 >/dev/null 2>&1 || die "python3 not found on PATH"
command -v keytool >/dev/null 2>&1 || die "keytool not found on PATH"
for t in "$AAPT2" "$D8" "$ZIPALIGN" "$APKSIGNER"; do
    [ -x "$t" ] || die "missing tool: $t (set ANDROID_HOME / BUILD_TOOLS_VERSION)"
done
[ -f "$ANDROID_JAR" ] || die "android.jar not found: $ANDROID_JAR"
[ -x "$GEN" ] || die "missing gen_snapshot: $GEN (see .cache/flutter-1/)"
[ -f "$FLUTTER_JAR" ] || die "missing flutter.jar: $FLUTTER_JAR"
[ -f "$CACHE/engine/patched/flutter_patched_sdk_product/platform_strong.dill" ] \
    || die "missing flutter_patched_sdk_product (see .cache/flutter-1/)"
[ -f "$APP_DIR/lib/main.dart" ] || die "missing app source"

mkdir -p "$OUT_DIR"
WORK="$OUT_DIR/work-flutter-$VARIANT"
rm -rf "$WORK"
mkdir -p "$WORK"/{compiled,gen,classes,dex,lib/"$ABI",assets/flutter_assets,flutter-assets}

# --- AndroidX closure (generated from the local Gradle module cache) ----------
ANDROIDX="$CACHE/androidx.jar"
if [ ! -f "$ANDROIDX" ]; then
    log "generating AndroidX closure (tools/flutter_androidx.py)"
    python3 "$ROOT/tools/flutter_androidx.py" "$ANDROIDX" \
        --gradle-cache "${ANDROIDX_GRADLE_CACHE:-$HOME/.gradle/caches/modules-2/files-2.1}" \
        || die "AndroidX resolution failed"
fi

# --- 1. Dart kernel (dart:ui only; no package:flutter) ------------------------
log "[$VARIANT] compiling Dart kernel"
DART_SDK="${DART_SDK:-/opt/dart-sdk}"
DART_AOT="$DART_SDK/bin/dartaotruntime"
FRONTEND="$DART_SDK/bin/snapshots/frontend_server_aot.dart.snapshot"
[ -x "$DART_AOT" ] || die "dartaotruntime not found: $DART_AOT"
[ -f "$FRONTEND" ] || die "frontend_server snapshot not found: $FRONTEND"
PATCHED="$CACHE/engine/patched/flutter_patched_sdk_product"
"$DART_AOT" "$FRONTEND" \
    --sdk-root "$PATCHED" \
    --platform "$PATCHED/platform_strong.dill" \
    --target=flutter --aot --tfa --link-platform \
    --packages "$APP_DIR/package_config.json" \
    --output-dill "$WORK/app.dill" \
    "$APP_DIR/lib/main.dart" 2>&1 | tee "$WORK/kernel.log"
[ -f "$WORK/app.dill" ] || die "Dart kernel not produced"
log "[$VARIANT] app.dill: $(stat -c '%s' "$WORK/app.dill") bytes"

# --- 2. AOT snapshot -> libapp.so --------------------------------------------
log "[$VARIANT] AOT compiling libapp.so"
"$GEN" --snapshot_kind=app-aot-elf --elf="$WORK/lib/$ABI/libapp.so" --strip \
    "$WORK/app.dill" 2>&1 | tee "$WORK/gen_snapshot.log"
[ -f "$WORK/lib/$ABI/libapp.so" ] || die "libapp.so not produced"
log "[$VARIANT] libapp.so: $(stat -c '%s' "$WORK/lib/$ABI/libapp.so") bytes"

# --- 3. Engine .so from flutter.jar ------------------------------------------
log "[$VARIANT] extracting libflutter.so from flutter.jar"
unzip -o -j -q "$FLUTTER_JAR" "lib/$ABI/libflutter.so" -d "$WORK/lib/$ABI" \
    || die "libflutter.so not found in $FLUTTER_JAR"
[ -f "$WORK/lib/$ABI/libflutter.so" ] || die "libflutter.so not extracted"
log "[$VARIANT] libflutter.so: $(stat -c '%s' "$WORK/lib/$ABI/libflutter.so") bytes"

# --- 4. Minimal flutter_assets ----------------------------------------------
# AssetManifest.bin is a StandardMessageCodec-encoded empty map: type 13, size 0.
printf '\x0d\x00' > "$WORK/flutter-assets/AssetManifest.bin"
printf '[]' > "$WORK/flutter-assets/FontManifest.json"
: > "$WORK/flutter-assets/NOTICES"
cp "$WORK"/flutter-assets/* "$WORK/assets/flutter_assets/"

# --- 5. Java: MainActivity extends FlutterActivity --------------------------
log "[$VARIANT] compiling resources"
"$AAPT2" compile --dir "$APP_DIR/res" -o "$WORK/compiled.zip"

log "[$VARIANT] linking resources + manifest"
"$AAPT2" link \
    -o "$WORK/base.apk" \
    -I "$ANDROID_JAR" \
    --manifest "$APP_DIR/AndroidManifest.xml" \
    -R "$WORK/compiled.zip" \
    --java "$WORK/gen" \
    --min-sdk-version 26 \
    --target-sdk-version 34 \
    --auto-add-overlay

log "[$VARIANT] compiling java"
# shellcheck disable=SC2046
javac --release 11 -encoding UTF-8 \
    -cp "$ANDROID_JAR:$FLUTTER_JAR:$ANDROIDX" \
    -d "$WORK/classes" \
    $(find "$APP_DIR/src" "$WORK/gen" -name '*.java')
(cd "$WORK/classes" && jar cf "$WORK/app-classes.jar" .)

# --- 6. DEX: app + Flutter embedding + AndroidX ------------------------------
log "[$VARIANT] dexing (app + flutter.jar + androidx.jar)"
"$D8" --lib "$ANDROID_JAR" --min-api 26 --output "$WORK/dex" \
    "$WORK/app-classes.jar" "$FLUTTER_JAR" "$ANDROIDX" 2>"$WORK/d8.log" || {
        tail -60 "$WORK/d8.log" >&2; die "d8 failed"; }
grep -iE "warning: .*(missing|defined multiple)" "$WORK/d8.log" | head -10 || true
ls -l "$WORK"/dex/*.dex

# --- 7. Assemble + sign ------------------------------------------------------
log "[$VARIANT] assembling APK"
python3 "$ROOT/tools/apk_append.py" "$WORK/base.apk" \
    "$WORK/dex:." "$WORK/lib:lib" "$WORK/assets:assets"

if [ ! -f "$KEYSTORE" ]; then
    log "generating throwaway debug keystore"
    keytool -genkeypair -keystore "$KEYSTORE" \
        -storepass "$KEY_PASS" -keypass "$KEY_PASS" \
        -alias "$KEY_ALIAS" \
        -dname "CN=Android Debug,O=Android,C=US" \
        -keyalg RSA -keysize 2048 -validity 10000 \
        -deststoretype pkcs12 >/dev/null 2>&1 \
        || die "keytool failed to create $KEYSTORE"
fi

rm -f "$OUT" "$WORK/aligned.apk"
"$ZIPALIGN" -f 4 "$WORK/base.apk" "$WORK/aligned.apk"
"$APKSIGNER" sign \
    --ks "$KEYSTORE" \
    --ks-pass "pass:$KEY_PASS" \
    --key-pass "pass:$KEY_PASS" \
    --ks-key-alias "$KEY_ALIAS" \
    --v1-signing-enabled true \
    --v2-signing-enabled true \
    --v3-signing-enabled true \
    --out "$OUT" \
    "$WORK/aligned.apk"
"$APKSIGNER" verify --verbose "$OUT" >/dev/null
"$APKSIGNER" verify --print-certs "$OUT" | sed 's/^/    /'

log "[$VARIANT] badging:"
"$AAPT2" dump badging "$OUT" | sed 's/^/    /' | head -n 20
log "[$VARIANT] native libs + assets in APK:"
unzip -l "$OUT" | grep -E "lib/.*\.so|assets/flutter_assets|classes.*\.dex" | awk '{print "    "$1" "$4}'
log "[$VARIANT] -> $OUT ($(stat -c '%s' "$OUT") bytes)"
