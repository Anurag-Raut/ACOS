package dev.acos.fixtures.sqlitecrud;

import android.app.Activity;
import android.content.ContentValues;
import android.database.Cursor;
import android.database.sqlite.SQLiteDatabase;
import android.database.sqlite.SQLiteOpenHelper;
import android.os.Bundle;
import android.util.Log;
import android.view.View;
import android.widget.ArrayAdapter;
import android.widget.Button;
import android.widget.EditText;
import android.widget.ListView;
import android.widget.TextView;

import java.util.ArrayList;
import java.util.List;

/**
 * SQLite CRUD fixture. Plain framework APIs only (no Room, no AndroidX).
 *
 * Observable behaviour:
 *  - EditText id=item_input + Button id=add INSERT a row via
 *    android.database.sqlite.SQLiteOpenHelper / SQLiteDatabase / ContentValues
 *  - the ListView id=items is reloaded from a Cursor after every insert
 *  - the number of persisted rows is shown in TextView id=status
 *  - the database file lives under the app's own files dir, so a relaunch
 *    re-reads the rows (persistence, not just in-memory state)
 *  - lifecycle/actions log with tag "AcosSqlite"
 */
public class MainActivity extends Activity {
    private static final String TAG = "AcosSqlite";
    private static final String DB_NAME = "notes.db";
    private static final int DB_VERSION = 1;

    /** Minimal helper: one table, one TEXT column, autogenerated _id rowid. */
    static final class NotesDb extends SQLiteOpenHelper {
        NotesDb(android.content.Context context) {
            super(context, DB_NAME, null, DB_VERSION);
        }

        @Override
        public void onCreate(SQLiteDatabase db) {
            db.execSQL("CREATE TABLE notes (_id INTEGER PRIMARY KEY AUTOINCREMENT, body TEXT NOT NULL)");
            Log.i(TAG, "NotesDb.onCreate table=notes");
        }

        @Override
        public void onUpgrade(SQLiteDatabase db, int oldVersion, int newVersion) {
            db.execSQL("DROP TABLE IF EXISTS notes");
            onCreate(db);
        }
    }

    private NotesDb db;
    private EditText input;
    private ArrayAdapter<String> adapter;
    private TextView status;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        Log.i(TAG, "onCreate");
        setContentView(R.layout.main);
        input = (EditText) findViewById(R.id.item_input);
        status = (TextView) findViewById(R.id.status);
        adapter = new ArrayAdapter<String>(this, android.R.layout.simple_list_item_1,
                new ArrayList<String>());
        ((ListView) findViewById(R.id.items)).setAdapter(adapter);
        db = new NotesDb(this);
        // Force the open + onCreate path now, not lazily on first click.
        db.getWritableDatabase();
        Log.i(TAG, "db opened path=" + getDatabasePath(DB_NAME).getAbsolutePath());
        if (savedInstanceState != null) {
            String draft = savedInstanceState.getString("draft", "");
            input.setText(draft);
            Log.i(TAG, "restored draft=" + draft);
        }
        ((Button) findViewById(R.id.add)).setOnClickListener(new View.OnClickListener() {
            @Override
            public void onClick(View v) {
                addNote();
            }
        });
        reload();
    }

    private void addNote() {
        String body = input.getText().toString().trim();
        if (body.isEmpty()) {
            Log.i(TAG, "add skipped empty");
            return;
        }
        ContentValues values = new ContentValues();
        values.put("body", body);
        long id = db.getWritableDatabase().insert("notes", null, values);
        Log.i(TAG, "insert id=" + id + " body=" + body);
        input.setText("");
        reload();
    }

    private void reload() {
        List<String> rows = new ArrayList<String>();
        Cursor cursor = db.getReadableDatabase().query("notes",
                new String[] {"_id", "body"}, null, null, null, null, "_id ASC");
        try {
            while (cursor.moveToNext()) {
                rows.add(cursor.getLong(0) + ": " + cursor.getString(1));
            }
        } finally {
            cursor.close();
        }
        adapter.clear();
        adapter.addAll(rows);
        if (rows.isEmpty()) {
            adapter.add(getString(R.string.empty));
        }
        status.setText("rows=" + rows.size());
        Log.i(TAG, "reload rows=" + rows.size());
    }

    @Override
    protected void onSaveInstanceState(Bundle outState) {
        super.onSaveInstanceState(outState);
        String draft = input == null ? "" : input.getText().toString();
        outState.putString("draft", draft);
        Log.i(TAG, "onSaveInstanceState draft=" + draft);
    }

    @Override
    protected void onStart() {
        super.onStart();
        Log.i(TAG, "onStart");
    }

    @Override
    protected void onResume() {
        super.onResume();
        Log.i(TAG, "onResume");
    }

    @Override
    protected void onPause() {
        super.onPause();
        Log.i(TAG, "onPause");
    }

    @Override
    protected void onStop() {
        super.onStop();
        Log.i(TAG, "onStop");
    }

    @Override
    protected void onDestroy() {
        super.onDestroy();
        Log.i(TAG, "onDestroy");
        if (db != null) {
            db.close();
            Log.i(TAG, "db closed");
        }
    }
}
