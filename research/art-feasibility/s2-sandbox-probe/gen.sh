#!/usr/bin/env bash
# gen.sh -- turn the real `acos-art` bwrap argv (argv-real.txt, captured with
# ACOS_ART_DEBUG_ARGV=1) into a replayable script.
#
# Emits ./bwrap-shape.sh, which:
#   * contains the *exact* argv shape from crates/acos-art/src/lib.rs:657-773,
#   * lets the caller inject extra flags right after `bwrap`   ($S2_EXTRA),
#   * lets the caller replace everything after `--`            (prog + args),
#   * always runs inside tools/guard/guarded.sh --mem $S2_MEM --time $S2_TIME.
#
# Nothing in crates/ is touched; argv-real.txt is the ground truth.
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$DIR/../../.." && pwd)"
IN="$DIR/argv-real.txt"
OUT="$DIR/bwrap-shape.sh"

python3 - "$IN" "$OUT" "$ROOT" <<'PY'
import shlex, sys, pathlib
src, out, root = sys.argv[1], sys.argv[2], sys.argv[3]
line = pathlib.Path(src).read_text().strip()
assert line.startswith("bwrap "), line[:40]
argv = shlex.split(line)[1:]          # drop the leading `bwrap`

# split at the first `--` that terminates bwrap's own options
i = argv.index("--")
flags, prog = argv[:i], argv[i + 1:]
# everything after the guest program is dalvikvm's argv; drop it, keep flags
assert prog, prog
q = lambda xs: " ".join(shlex.quote(x) for x in xs)

script = f"""#!/usr/bin/env bash
# GENERATED by gen.sh from argv-real.txt -- do not hand-edit.
#
# bwrap argv shape = Sandbox::command(), crates/acos-art/src/lib.rs:657-773,
# captured from a real 01_hello run (27/27 corpus path).
#
#   S2_EXTRA   extra bwrap flags, inserted immediately after `bwrap`
#   S2_MEM     guarded.sh --mem   (default 2G)
#   S2_TIME    guarded.sh --time  (default 120)
#   args...    guest program + argv (replaces dalvikvm64 ...)
#
# usage: ./bwrap-shape.sh -- /system/bin/sh -c 'id'
set -uo pipefail
ROOT={shlex.quote(root)}
EXTRA=${{S2_EXTRA:-}}
MEM=${{S2_MEM:-2G}}
TIME=${{S2_TIME:-120}}
[ $# -gt 0 ] && [ "$1" = "--" ] && shift
GUEST=("$@")
[ ${{#GUEST[@]}} -eq 0 ] && {{ echo "no guest command" >&2; exit 2; }}

ARGV=({q(flags)})
# shellcheck disable=SC2086
exec "$ROOT/tools/guard/guarded.sh" --mem "$MEM" --time "$TIME" -- \\
    bwrap $EXTRA "${{ARGV[@]}}" -- "${{GUEST[@]}}"
"""
pathlib.Path(out).write_text(script)
# second copy: same argv, no tools/guard/guarded.sh wrapper. Used only by p6 (orphan
# survival), where guarded.sh's process-group cleanup would mask the answer.
# The p6 script itself is run under tools/guard/guarded.sh from the caller.
raw = script.replace('exec "$ROOT/tools/guard/guarded.sh" --mem "$MEM" --time "$TIME" -- \\\n    bwrap', 'exec bwrap')
raw = raw.replace("# GENERATED by gen.sh", "# GENERATED by gen.sh (RAW: no guarded.sh wrapper -- for p6 only)")
pathlib.Path(out.replace("bwrap-shape.sh", "bwrap-raw.sh")).write_text(raw)
pathlib.Path(out.replace("bwrap-shape.sh", "bwrap-raw.sh")).chmod(0o755)
pathlib.Path(out).chmod(0o755)
print(f"wrote {out}: {len(flags)} bwrap flags, guest program was {prog[0]}")
PY
